"""Type stubs (``.pyi``) for the ``cerulion.msgs`` classes.

One renderer serves both kinds: the stubs the wheel ships for the built-in
packages (``cerulion/msgs/<package>.pyi``) and the ones a workspace gets at
``<workspace>/.cerulion/python/cerulion-stubs/``, a PEP 561 partial stub
package that type checkers read ahead of the wheel and fall back from for
every package the workspace leaves as built.

Each field is typed from the resolved layout as the view returns it: fixed
scalars as ``int``/``float``/``bool``, strings as ``str``, fixed and primitive
arrays as NumPy arrays (assignable from any array-like), nested messages as
their class, and ``string[]``/``Type[]`` fields as a list. Getters are typed
as a received message reads: on a loan a variable nested message, a
``string[]`` and a ``Type[]`` field read as their pre-framed ``memoryview``
instead, and their setters take those bytes.
"""

from __future__ import annotations

import keyword
import os
import shutil

from cerulion import _native
from cerulion._typed import Message, SchemaSet, _nested_name

_HEADER = "# Generated by cerulion.msgs from the resolved message set. Do not edit.\n"

_PY_SCALAR = {
    "Bool": "bool",
    "I8": "int",
    "U8": "int",
    "I16": "int",
    "U16": "int",
    "I32": "int",
    "U32": "int",
    "I64": "int",
    "U64": "int",
    "F32": "float",
    "F64": "float",
}
# Every name a stub imports is underscored, so no message class (a user's
# `pkg/Message`, `pkg/Any`) can shadow it.
_NP_SCALAR = {
    "Bool": "_np.bool_",
    "I8": "_np.int8",
    "U8": "_np.uint8",
    "I16": "_np.int16",
    "U16": "_np.uint16",
    "I32": "_np.int32",
    "U32": "_np.uint32",
    "I64": "_np.int64",
    "U64": "_np.uint64",
    "F32": "_np.float32",
    "F64": "_np.float64",
}
_STR_SET = "str | bytes"
_BYTES_SET = "bytes | bytearray | memoryview"
_RESERVED = frozenset(name for name in dir(Message) if not name.startswith("__"))


def _split(qualified):
    from cerulion.msgs import _split as split

    return split(qualified)


class _Refs:
    """The names one stub module uses for other modules' classes."""

    def __init__(self, module):
        self.module = module
        self.imports = set()

    def cls(self, schemas, nested, parent):
        try:
            qualified = _nested_name(schemas, nested, parent)
        except _native.SchemaError:
            return "_Message"
        split = _split(qualified)
        if split is None:
            return "_Message"
        module, leaf = split
        if not _nameable(leaf) or (module is not None and not _nameable(module)):
            return "_Message"
        if module == self.module:
            return leaf
        if module is None:
            self.imports.add("import cerulion.msgs as _msgs")
            return f"_msgs.{leaf}"
        self.imports.add(f"from cerulion.msgs import {module} as _m_{module}")
        return f"_m_{module}.{leaf}"


def _types(schemas, refs, parent, field_type, fixed_section):
    """``(getter type, setter type or None)`` of one field."""
    if isinstance(field_type, str):
        if field_type in _PY_SCALAR:
            return _PY_SCALAR[field_type], _PY_SCALAR[field_type]
        if field_type == "String":
            return "str", _STR_SET
        if field_type == "Bytes":
            return "memoryview", _BYTES_SET
        return "_Any", "_Any"
    if "StringFixed" in field_type:
        return "str", _STR_SET
    if "Nested" in field_type:
        cls = refs.cls(schemas, field_type["Nested"], parent)
        if fixed_section:
            return cls, None
        return cls, "_Mapping[str, _Any] | bytes"
    key = "FixedArray" if "FixedArray" in field_type else "DynamicArray"
    if key not in field_type:
        return "_Any", "_Any"
    element = field_type[key]["element_type"]
    if isinstance(element, str) and element in _NP_SCALAR:
        return f"_NDArray[{_NP_SCALAR[element]}]", "_ArrayLike"
    if fixed_section:
        # A fixed array of fixed strings or fixed nested messages is one
        # NumPy array over the fixed section.
        if isinstance(element, dict) and "StringFixed" in element:
            return "_NDArray[_np.bytes_]", "_ArrayLike"
        return "_NDArray[_np.void]", "_ArrayLike"
    if element == "String" or (isinstance(element, dict) and "StringFixed" in element):
        return "list[str]", "bytes"
    if isinstance(element, dict) and "Nested" in element:
        cls = refs.cls(schemas, element["Nested"], parent)
        return f"list[{cls}]", "bytes"
    return "_Any", "bytes"


def _render_class(schemas, refs, qualified, leaf):
    layout = schemas.layout(qualified)
    lines = [f"class {leaf}(_Message):", f'    """The {qualified} message."""']
    fields = [(field, True) for field in layout.fixed_fields]
    fields += [(field, False) for field in layout.variable_fields]
    for field, fixed_section in fields:
        name = field.name
        if keyword.iskeyword(name) or name in _RESERVED or not name.isidentifier():
            lines.append(f"    # field {name!r}: read and write it as message[{name!r}]")
            continue
        getter, setter = _types(schemas, refs, qualified, field.field_type, fixed_section)
        lines.append("    @property")
        lines.append(f"    def {name}(self) -> {getter}: ...")
        if setter is not None:
            lines.append(f"    @{name}.setter")
            lines.append(f"    def {name}(self, value: {setter}) -> None: ...")
    return "\n".join(lines) + "\n"


def _members(schemas, module):
    from cerulion.msgs import _split as split

    members = {}
    for qualified in schemas.names():
        parts = split(qualified)
        if parts is not None and parts[0] == module and _nameable(parts[1]):
            members[parts[1]] = qualified
    return members


def _nameable(name):
    """Whether a stub can declare ``name``: an identifier, not a keyword."""
    return name.isidentifier() and not keyword.iskeyword(name)


def render_module(schemas, module):
    """The stub text of module ``module`` (``None`` for the top of
    ``cerulion.msgs``) over ``schemas``."""
    refs = _Refs(module)
    classes = [
        _render_class(schemas, refs, qualified, leaf)
        for leaf, qualified in sorted(_members(schemas, module).items())
    ]
    head = [
        _HEADER,
        "from typing import Any as _Any, Mapping as _Mapping\n",
        "\n",
        "import numpy as _np\n",
        "from numpy.typing import ArrayLike as _ArrayLike, NDArray as _NDArray\n",
        "\n",
        "from cerulion import Message as _Message, SchemaSet as _SchemaSet\n",
    ]
    for line in sorted(refs.imports):
        head.append(line + "\n")
    if module is None:
        head.extend(
            [
                "\n",
                "def _bind_workspace(root: str, reload: bool = True) -> _SchemaSet: ...\n",
                "def _schemas_for(root: str) -> _SchemaSet: ...\n",
                "def _message_set() -> _SchemaSet: ...\n",
                "def _workspace_root() -> str | None: ...\n",
                "def _fill(namespace: dict[str, _Any], schemas: _SchemaSet | None = None) -> None: ...\n",
            ]
        )
    body = "\n\n".join(classes)
    return "".join(head) + ("\n\n" + body if body else "")


def _modules(schemas):
    from cerulion.msgs import _split as split

    modules = set()
    for qualified in schemas.names():
        parts = split(qualified)
        if parts is not None and parts[0] is not None and _nameable(parts[0]):
            modules.add(parts[0])
    return modules


def render_package_source(module):
    """The source of the wheel's ``cerulion/msgs/<module>.py``: the module
    fills itself from the set ``cerulion.msgs`` resolves against when it is
    imported, so a workspace override reaches it too."""
    return (
        _HEADER
        + f'"""The {module} message classes."""\n\n'
        + "from cerulion.msgs import _fill\n\n"
        + "_fill(globals())\n"
    )


def builtin_files():
    """``{file name: text}`` of every file ``write_builtin_stubs`` writes."""
    builtins = SchemaSet.builtins()
    files = {"__init__.pyi": render_module(builtins, None)}
    for module in sorted(_modules(builtins)):
        files[f"{module}.pyi"] = render_module(builtins, module)
        files[f"{module}.py"] = render_package_source(module)
    return files


def write_builtin_stubs(directory):
    """Write the wheel's built-in package files into ``directory`` (the
    ``cerulion/msgs`` source directory): ``__init__.pyi``, and per built-in
    package its ``<package>.py`` module and ``<package>.pyi`` stub."""
    for name, text in builtin_files().items():
        _write(os.path.join(directory, name), text)


def write_workspace_stubs(out_dir, schemas=None):
    """Write the partial stub package of the bound workspace (or of
    ``schemas``) under ``out_dir``: ``cerulion-stubs/py.typed`` reading
    ``partial`` and a stub for each package that differs from the wheel's
    built-in one (a workspace package, a built-in package an override
    changed) plus the top of ``cerulion.msgs`` when the workspace has
    package-less messages. The ``cerulion-stubs`` directory is replaced.
    Returns the paths written."""
    if schemas is None:
        from cerulion.msgs import _message_set

        schemas = _message_set()
    builtins = SchemaSet.builtins()
    root = os.path.join(out_dir, "cerulion-stubs")
    if os.path.isdir(root):
        shutil.rmtree(root)
    written = [_write(os.path.join(root, "py.typed"), "partial\n")]
    if _members(schemas, None):
        written.append(
            _write(os.path.join(root, "msgs", "__init__.pyi"), render_module(schemas, None))
        )
    for module in sorted(_modules(schemas) | _modules(builtins)):
        text = render_module(schemas, module)
        if module in _modules(builtins) and text == render_module(builtins, module):
            continue
        written.append(_write(os.path.join(root, "msgs", f"{module}.pyi"), text))
    return written


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return path
