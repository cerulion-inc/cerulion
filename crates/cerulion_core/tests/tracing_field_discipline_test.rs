#[test]
fn tracing_calls_use_structured_fields_not_interpolation() {
    let declared: BTreeMap<&str, &Declared> = DECLARED_SITES.iter().map(|d| (d.path, d)).collect();
    assert_eq!(
        declared.len(),
        DECLARED_SITES.len(),
        "DECLARED_SITES has a duplicate path — the later entry silently \
         overrides the earlier one"
    );
    for d in DECLARED_SITES {
        assert!(
            d.reason.trim().len() >= 20,
            "{}: a declared site needs a REASON, not a placeholder ({:?})",
            d.path,
            d.reason
        );
        assert!(
            d.interpolation + d.pass_through > 0,
            "{}: a declared entry with zero sites is stale — delete it",
            d.path
        );
    }

    let mut found: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    let mut detail: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut found_keys: BTreeMap<String, Vec<String>> = BTreeMap::new();
    // An ALL-CAPS capture is exempted as a compile-time
    // constant, so the exemption must be BACKED by a declaration somewhere in
    // the tree rather than granted on casing alone. Computed once — the set is
    // the union over every walked file (see `declared_const_names`).
    let declared_consts = declared_const_names();
    let mut unverified: Vec<String> = Vec::new();
    let mut non_literal: Vec<String> = Vec::new();
    for rel in library_src_files() {
        let st = stripped_for(&rel);
        for site in tracing_sites(&st) {
            if site.non_literal_message {
                non_literal.push(format!(
                    "    {rel}:{} {}! has a NON-LITERAL message argument (a `concat!` or \
                     another macro). tracing forwards it to `format_args!`, so it can \
                     interpolate — this walk cannot read it, and classified the site Clean \
                     while mis-reading the trailing format ARG as a field.",
                    site.line, site.level
                ));
            }
            for name in unverified_const_captures(&site.message, &declared_consts) {
                unverified.push(format!(
                    "    {rel}:{} {}! captures `{{{name}}}`, which LOOKS like a compile-time \
                     constant but resolves to no `const`/`static` declared in the workspace",
                    site.line, site.level
                ));
            }
            let slot = found.entry(rel.clone()).or_insert((0, 0));
            match site.class {
                SiteClass::Clean => {}
                SiteClass::Interpolation => slot.0 += 1,
                SiteClass::PassThrough => slot.1 += 1,
            }
            if site.class != SiteClass::Clean {
                found_keys
                    .entry(rel.clone())
                    .or_default()
                    .push(message_key(&site.message));
            }
            if site.class != SiteClass::Clean {
                let msg: String = site.message.chars().take(90).collect();
                detail.entry(rel.clone()).or_default().push(format!(
                    "    {rel}:{} {}! [{:?}] {msg}",
                    site.line, site.level, site.class
                ));
            }
        }
        found.retain(|_, v| *v != (0, 0));
    }

    let mut problems: Vec<String> = Vec::new();

    if !non_literal.is_empty() {
        problems.push(format!(
            "a tracing message must be a STRING LITERAL the walk can read; these are not, \
             so neither arm can see what they interpolate:\n{}\n  FIX: write the message \
             as a literal and lift the values into structured fields.",
            non_literal.join("\n")
        ));
    }

    if !unverified.is_empty() {
        problems.push(format!(
            "an ALL-CAPS capture is exempted because it renders at COMPILE time; these do \
             not resolve to any declared constant, so the exemption is unearned and the \
             value may be a runtime one:\n{}\n  FIX: lift the value into a structured \
             field, or give it a real `const`.",
            unverified.join("\n")
        ));
    }

    // The site-level comparison. This is the arm that
    // detects replacement; the count comparison below stays as a cheap
    // cross-check and for its better diagnostics on the pure add/retire cases.
    for (rel, keys) in &found_keys {
        let Some(d) = declared.get(rel.as_str()) else {
            continue; // an undeclared file is reported by the count arm below
        };
        let mut have: Vec<String> = keys.clone();
        let mut want: Vec<String> = d.messages.iter().map(|m| (*m).to_string()).collect();
        have.sort();
        want.sort();
        if have == want {
            continue;
        }
        let mut lines = Vec::new();
        for k in have.iter().filter(|k| !want.contains(k)) {
            lines.push(format!("    + NEW  {k}"));
        }
        for k in want.iter().filter(|k| !have.contains(k)) {
            lines.push(format!("    - GONE {k}"));
        }
        let paste: String = have
            .iter()
            .map(|k| format!("            {k:?},\n"))
            .collect();
        problems.push(format!(
            "{rel}: the DECLARED SITE SET does not match what the walk found.\n{}\n  \
             A NEW interpolating message cannot be laundered into the budget by retiring\n  \
             another one in the same file — the debt is pinned per SITE, not per count.\n  \
             If you RETIRED a site, drop its line; if a message was REWORDED, update it.\n  \
             A `+ NEW` line is a violation to FIX, never to paste in.\n  \
             Current set, paste-ready:\n        messages: &[\n{paste}        ],",
            lines.join("\n")
        ));
    }

    for (rel, (interp, pass)) in &found {
        let want = declared.get(rel.as_str());
        let (want_i, want_p) = want
            .map(|d| (d.interpolation, d.pass_through))
            .unwrap_or((0, 0));
        if (*interp, *pass) == (want_i, want_p) {
            continue;
        }
        let lines = detail.get(rel).cloned().unwrap_or_default().join("\n");
        if want.is_none() {
            problems.push(format!(
                "{rel}: {interp} interpolating + {pass} pass-through tracing message(s), \
                 and this file is NOT in DECLARED_SITES.\n{lines}\n  FIX: put the value in a \
                 STRUCTURED FIELD and keep the message constant —\n       \
                 `tracing::warn!(topic = %topic, \"publisher created\")`, never\n       \
                 `tracing::warn!(\"publisher created for topic {{topic}}\")`.\n  \
                 A `{{SCREAMING_CONST}}` capture is always fine (it renders at compile time).\n  \
                 If the message genuinely IS the value (a forwarded log line, a whole \
                 remediation\n  paragraph a helper built), add a DECLARED_SITES entry with the \
                 reason."
            ));
        } else if (*interp < want_i && *pass > want_p) || (*pass < want_p && *interp > want_i) {
            // One class shrank while the other
            // grew. Sending this shape to the "a NEW message
            // interpolates" arm would misdirect — the correct reading is that
            // a site changed CLASS (or one was retired and a different-class one
            // added). The site-set arm above already names which messages moved.
            problems.push(format!(
                "{rel}: declared {want_i} interpolating + {want_p} pass-through, found \
                 {interp} + {pass} — one class SHRANK while the other GREW, so a site \
                 changed CLASS (or one was retired and another added). See the site-set \
                 report above for which messages moved."
            ));
        } else if *interp < want_i && *pass <= want_p || *pass < want_p && *interp <= want_i {
            problems.push(format!(
                "{rel}: declared {want_i} interpolating + {want_p} pass-through, but only \
                 {interp} + {pass} remain — someone RETIRED debt. Lower the DECLARED_SITES \
                 counts to {interp} / {pass} (or delete the entry) so the ledger stays accurate."
            ));
        } else {
            problems.push(format!(
                "{rel}: declared {want_i} interpolating + {want_p} pass-through, found \
                 {interp} + {pass} — a NEW tracing message interpolates a runtime value.\n{lines}\n  \
                 FIX: lift the value into a structured field; do NOT raise the declared count."
            ));
        }
    }

    for d in DECLARED_SITES {
        if !found.contains_key(d.path) {
            problems.push(format!(
                "{}: DECLARED_SITES claims {} interpolating + {} pass-through site(s), but the \
                 walk found NONE. Either the file was cleaned (delete the entry) or the walk no \
                 longer reaches it (a renamed/moved file, or a SKIPPED_TREES entry that now \
                 swallows it) — an inventory entry that describes nothing pre-authorises a \
                 future violation.",
                d.path, d.interpolation, d.pass_through
            ));
        }
    }

    assert!(
        problems.is_empty(),
        "tracing message discipline (CLAUDE.md → Logging: \"Never use string \
         interpolation for data\"):\n\n{}\n",
        problems.join("\n\n")
    );
}

