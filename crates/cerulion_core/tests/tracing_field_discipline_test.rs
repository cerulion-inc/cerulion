fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("cerulion_core has a parent directory")
        .to_path_buf()
}

/// Every library `src/**/*.rs` in the workspace, repo-relative, sorted.
fn library_src_files() -> Vec<String> {
    let root = repo_root();
    let mut out = Vec::new();
    let mut stack = vec![root.clone()];
    while let Some(dir) = stack.pop() {
        let Ok(rd) = fs::read_dir(&dir) else { continue };
        for entry in rd.flatten() {
            let path = entry.path();
            let name = entry.file_name().to_string_lossy().to_string();
            if path.is_dir() {
                if SKIPPED_TREES.iter().any(|(d, _)| *d == name) {
                    continue;
                }
                stack.push(path);
            } else if name.ends_with(".rs") {
                let rel = path
                    .strip_prefix(&root)
                    .expect("under the repo root")
                    .to_string_lossy()
                    .replace('\\', "/");
                // Library source only: the path must pass through a `src`
                // directory. `tests/`, `build.rs` and bench targets are out.
                if rel.split('/').any(|seg| seg == "src") {
                    out.push(rel);
                }
            }
        }
    }
    out.sort();
    out
}

fn stripped_for(rel: &str) -> Stripped {
    let path = repo_root().join(rel);
    let src = fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {rel}: {e}"));
    let st = code_only(&src);
    assert_eq!(
        st.unclosed_depth, 0,
        "{rel}: the comment-stripped view did not finish BALANCED ({} unclosed `/*`), \
         so its tail was dropped and every assertion over it is vacuous. Fix the \
         source, or teach `code_only` the shape it mis-read.",
        st.unclosed_depth
    );
    st
}

