/// The stripped view plus the two things a caller must be able to check.
struct Stripped {
    /// Comments blanked; string/char literals kept VERBATIM.
    code: String,
    /// `true` at every byte index of `code` that lies inside a string literal.
    in_literal: Vec<bool>,
    /// Unclosed `/*` depth at EOF. Anything but 0 means the tail was dropped.
    unclosed_depth: usize,
}

/// A comment-stripped view of Rust source that KEEPS string literals.
///
/// Every other structural walk in this repo (`completions_test.rs`,
/// `convergence_adoption_test.rs`, `cdylib_iox2_log_level_test.rs`) DISCARDS
/// literals, because those walks hunt for tokens and a token quoted in prose is
/// a false positive. This walk is the opposite shape: the literal is the
/// EVIDENCE. So literals are preserved, and the positions that are inside one
/// are recorded in `in_literal` so the macro scanner can refuse to match there —
/// without that mask, `cerulion_core/src/codegen/generator/structs.rs`, which
/// EMITS `tracing::warn!(` as text into a generated file, would be read as a
/// call site of its own.
///
/// Modelled, each because the alternative silently loses or fabricates coverage:
///
/// * Block comments NEST in Rust ⇒ depth-tracked.
/// * RAW string literals (`r"…"`, `r#"…"#`, `br#"…"#`) ⇒ their contents are not
///   escape-processed, so a `\"` inside one does NOT continue the literal.
/// * CHAR literals holding a quote (`'"'`) ⇒ a lone `"` there would otherwise
///   open the string arm and swallow the file to the next quote, at
///   `depth == 0`, where the unclosed-depth guard cannot see it. Only the short
///   shapes are consumed, so a LIFETIME (`&'static str`) is never eaten.
/// * The unclosed depth is REPORTED, so a truncated view fails LOUDLY instead of
///   masquerading as a clean one.
fn code_only(src: &str) -> Stripped {
    let bytes = src.as_bytes();
    let mut out = String::with_capacity(src.len());
    let mut lit = Vec::with_capacity(src.len());
    let mut i = 0usize;
    let mut depth = 0usize;

    // Push `text`, marking every byte as inside-a-literal or not.
    macro_rules! push {
        ($text:expr, $inside:expr) => {{
            let t: &str = $text;
            out.push_str(t);
            lit.resize(out.len(), $inside);
        }};
    }

    while i < bytes.len() {
        if depth == 0 {
            // CHAR literal — only `'x'` / `'\x'`, so lifetimes survive.
            if bytes[i] == b'\'' {
                let close = if bytes.get(i + 1) == Some(&b'\\') {
                    (bytes.get(i + 3) == Some(&b'\'')).then_some(i + 3)
                } else {
                    (bytes.get(i + 2) == Some(&b'\'')).then_some(i + 2)
                };
                if let Some(end) = close {
                    push!(&src[i..=end], true);
                    i = end + 1;
                    continue;
                }
                // No closer in range ⇒ a lifetime; fall through.
            }
            // RAW string literal: optional `b`, `r`, N `#`, then `"`.
            let raw_start = if bytes[i] == b'b' && bytes.get(i + 1) == Some(&b'r') {
                Some(i + 1)
            } else if bytes[i] == b'r' {
                Some(i)
            } else {
                None
            };
            if let Some(rs) = raw_start {
                // A bare `r`/`br` must not be an identifier tail (`for`, `char`).
                let prev_is_ident = i > 0 && {
                    let p = bytes[i - 1];
                    p.is_ascii_alphanumeric() || p == b'_'
                };
                let mut j = rs + 1;
                while j < bytes.len() && bytes[j] == b'#' {
                    j += 1;
                }
                if !prev_is_ident && j < bytes.len() && bytes[j] == b'"' {
                    let hashes = j - rs - 1;
                    let mut k = j + 1;
                    'raw: while k < bytes.len() {
                        if bytes[k] == b'"' {
                            let mut h = 0usize;
                            while h < hashes && k + 1 + h < bytes.len() && bytes[k + 1 + h] == b'#'
                            {
                                h += 1;
                            }
                            if h == hashes {
                                k = k + 1 + hashes;
                                break 'raw;
                            }
                        }
                        k += 1;
                    }
                    let end = k.min(bytes.len());
                    push!(&src[i..end], true);
                    i = end;
                    continue;
                }
            }
            // Regular (or byte) string literal.
            if bytes[i] == b'"' {
                let mut k = i + 1;
                while k < bytes.len() {
                    match bytes[k] {
                        b'\\' => k += 2,
                        b'"' => {
                            k += 1;
                            break;
                        }
                        _ => k += 1,
                    }
                }
                let end = k.min(bytes.len());
                push!(&src[i..end], true);
                i = end;
                continue;
            }
            if bytes[i..].starts_with(b"//") {
                while i < bytes.len() && bytes[i] != b'\n' {
                    i += 1;
                }
                continue;
            }
        }
        if bytes[i..].starts_with(b"/*") {
            depth += 1;
            i += 2;
            continue;
        }
        if depth > 0 && bytes[i..].starts_with(b"*/") {
            depth -= 1;
            i += 2;
            continue;
        }
        if depth == 0 {
            let ch = src[i..].chars().next().expect("valid utf-8 boundary");
            let mut buf = [0u8; 4];
            push!(ch.encode_utf8(&mut buf), false);
            i += ch.len_utf8();
        } else {
            // Keep line structure inside a block comment so line numbers hold.
            if bytes[i] == b'\n' {
                push!("\n", false);
            }
            i += 1;
        }
    }
    Stripped {
        code: out,
        in_literal: lit,
        unclosed_depth: depth,
    }
}

