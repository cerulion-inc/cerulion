//! The structured-logging rule (`AGENTS.md`, Conventions → **Logging**) as
//! a GATE instead of prose.
//!
//! The rule has two halves and this walk enforces BOTH:
//!
//! 1. *"Never use string interpolation for data"* — a datum belongs in a
//!    structured field (`topic = %topic`), never spliced into the message text.
//!    An interpolated message is one opaque string to every consumer: an
//!    operator cannot `grep topic=`, a JSON subscriber gets no key, and the
//!    per-site `logs_contain(..)` oracles this repo leans on have to match
//!    whatever the value happened to be.
//! 2. *"Standard Fields"* — one spelling per quantity. Left to convention, three
//!    reporting modules spell one counter FOUR ways (`total_mismatches=`, `total_drops=`,
//!    `total_failures=`, `total_rejects=`), which is exactly why a walk
//!    is the right enforcement: operators grep BY KEY, so "how bad has this got?"
//!    must not need four queries across one robot's logs.
//!
//! # What the first arm actually forbids
//!
//! A tracing message literal must be a CONSTANT string. Three shapes are
//! distinguished, because they are three different things:
//!
//! * `{}` / `{0}` / `{:?}` — a POSITIONAL splice of a runtime value.
//! * `{some_local}` — an INLINE CAPTURE of a runtime value. Same defect, newer
//!   syntax; a walk that only looked for `{}` would miss 3 of every 4 sites
//!   measured in this tree.
//! * `{SCREAMING_CONST}` — an inline capture of a compile-time `const`. This is
//!   ALLOWED without an inventory entry, because nothing about the *data* is
//!   being smuggled into the message. It is NOT allowed on casing alone, which
//!   is a convention and not a fact: the capture must resolve to a `const` or
//!   `static` declared in the walked tree (see [`declared_const_names`]), and a
//!   `static` with INTERIOR MUTABILITY does not count — an `AtomicU64` rendered
//!   as `{X:?}` is runtime data wearing a constant's spelling. The idiom is
//!   load-bearing here: a const message (`PERMISSIVE_EGRESS_NOTICE`,
//!   `INGRESS_HOLD_CEILING_MSG`, …) is how a test pins a line by IDENTITY
//!   rather than by re-typing its prose, and how one sentence names an env var
//!   (`{CERULION_NETWORK}`) without two copies drifting.
//!
//! A site carrying a non-const placeholder falls into one of two classes, and
//! they are separated because their remedies differ:
//!
//! * **Interpolation** — prose AND a runtime placeholder (`"publisher created
//!   for topic {}"`). This is the logging convention's forbidden example verbatim. Fix: lift the
//!   value into a field.
//! * **PassThrough** — the message is ONLY a placeholder (`warn!("{}", msg)`,
//!   `warn!("{msg}")`). The value IS the message: a forwarded foreign log line
//!   (`iceoryx_logger.rs` hands iceoryx2's own text to `tracing`), or a
//!   remediation paragraph a pure function built. There is no datum to lift —
//!   `message = %msg` with an empty message is strictly worse — so these are
//!   declared with a reason rather than "fixed".
//!
//! # The ledger is a RATCHET, and its counts are EXACT
//!
//! [`DECLARED_SITES`] records, per file, how many of each class exist today.
//! The comparison is EQUALITY, not a ceiling: a file that gains a site fails
//! ("a NEW interpolation"), and a file that LOSES one fails too ("you fixed one
//! — lower the count"). A ceiling would let the ledger rot into a permanent
//! over-grant; equality keeps it an accurate, shrinking debt list.
//!
//! Measured at adoption: **65** Interpolation + **13** PassThrough sites across
//! 8 crates. Every `cerulion_core` Interpolation site is fixed (the crate
//! that owns the rule and the hot path) and the rest are declared — see
//! [`DECLARED_SITES`] for the full cross-crate list.

