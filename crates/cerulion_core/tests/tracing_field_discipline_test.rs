#[test]
fn standard_field_names_are_spelled_consistently() {
    let allow: BTreeMap<&str, &str> = FIELD_NAME_ALLOWLIST.iter().copied().collect();
    for (_, why) in FIELD_NAME_ALLOWLIST {
        assert!(
            why.trim().len() >= 20,
            "every FIELD_NAME_ALLOWLIST entry needs a reason"
        );
    }
    // A forbidden spelling must not also be allowlisted — that would make the
    // whole arm silently vacuous for that name.
    for (standard, forbidden) in STANDARD_FIELDS {
        for f in *forbidden {
            assert!(
                !allow.contains_key(f),
                "`{f}` is BOTH forbidden (near-spelling of `{standard}`) and allowlisted"
            );
        }
    }

    let mut offences: Vec<String> = Vec::new();
    let mut standard_seen = 0usize;
    for rel in library_src_files() {
        let st = stripped_for(&rel);
        for site in tracing_sites(&st) {
            for f in &site.fields {
                if STANDARD_FIELDS.iter().any(|(s, _)| s == f) {
                    standard_seen += 1;
                }
                if allow.contains_key(f.as_str()) {
                    continue;
                }
                for (standard, forbidden) in STANDARD_FIELDS {
                    if forbidden.contains(&f.as_str()) {
                        offences.push(format!(
                            "    {rel}:{} {}! uses `{f}=` — the standard spelling for this \
                             quantity is `{standard}=`",
                            site.line, site.level
                        ));
                    }
                }
            }
        }
    }

    // Anti-vacuity: if the field parser broke, every absence above is free.
    assert!(
        standard_seen > 100,
        "the field parser found only {standard_seen} uses of the STANDARD field names \
         across the whole tree — it is broken, and the near-spelling assertions below \
         it are vacuous"
    );

    assert!(
        offences.is_empty(),
        "tracing field-name discipline (CLAUDE.md → Logging: \"Standard Fields\"). \
         Operators grep BY KEY, \
         so one quantity gets one spelling:\n\n{}\n\n  FIX: rename the field to the \
         standard spelling. If the quantity is genuinely DIFFERENT, add it to \
         FIELD_NAME_ALLOWLIST with a reason.",
        offences.join("\n")
    );
}

