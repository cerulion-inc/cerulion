/// A file's declared tracing-message debt.
struct Declared {
    /// Repo-relative path, `/`-separated.
    path: &'static str,
    /// Prose + a runtime placeholder — the forbidden interpolation shape. Must shrink.
    interpolation: usize,
    /// Message is ONLY a placeholder — the value IS the message.
    pass_through: usize,
    /// The message prefix of every declared site, so the
    /// debt is pinned per site and not merely per count.
    ///
    /// Counts alone cannot see REPLACEMENT. Retiring one declared interpolating
    /// site and adding a brand-new one elsewhere in the same file leaves
    /// `(interpolation, pass_through)` unchanged, so a new interpolated
    /// operator message passes green — flatly contradicting this module's own
    /// claim that "a file that gains a site fails". The exposed case is
    /// `graph_cmd.rs` (declared 9), which is a 14k-line file where the two
    /// edits need not be near each other.
    ///
    /// The identity is the MESSAGE, not the line: a message survives unrelated
    /// line drift, which is the whole reason a line number would be the wrong
    /// key. Compared as a MULTISET, so one file may legitimately declare the
    /// same key twice — which now means, and only means, that it really does
    /// carry the same message twice.
    ///
    /// A key is a readable PREFIX plus a DIGEST of the whole message (see
    /// [`message_key`]). The prefix alone is not enough of a key, and the
    /// hole it leaves is LIVE: `transport/network.rs` carries two
    /// DIFFERENT operator paragraphs that agree for more than
    /// [`MESSAGE_KEY_LEN`] characters, so they shared one key and a swap
    /// BETWEEN them was invisible to the multiset. The digest closes that by
    /// construction, and
    /// `two_sites_share_a_ledger_key_only_if_they_share_a_message` holds the
    /// line for every future pair.
    messages: &'static [&'static str],
    /// Why these are here. A blank reason is not acceptable.
    reason: &'static str,
}

/// How much of a message is SHOWN in a ledger key. Long enough that a human
/// reading `DECLARED_SITES` can tell which site a line is; short enough that
/// the array stays a list rather than a second copy of the operator prose.
///
/// This is a READABILITY budget, not the key's discriminating power — that is
/// the digest's job. A prefix length can only ever be "long enough for the
/// collisions we happen to have today", which is how the pair in
/// `state_arm_attach.rs` came to share a key.
const MESSAGE_KEY_LEN: usize = 60;

/// The stable identity of a site: a readable PREFIX of its message plus a
/// digest of the WHOLE message, both taken after whitespace collapse (so a
/// rustfmt re-wrap is the same site — the reason a line number would be the
/// wrong key).
///
/// # Why not the prefix alone
///
/// Because the ledger's whole claim is "a NEW interpolating message cannot be
/// laundered in by retiring another one in the same file", and a prefix cannot
/// support it: two sites whose messages agree for [`MESSAGE_KEY_LEN`]
/// characters produce ONE key, so swapping one for the other moves nothing the
/// multiset can see. That is not hypothetical — `transport/network.rs` ships
/// such a pair (two `ingress: local publisher mutex poisoned — validated frame
/// dropped …` paragraphs that diverge only in their trailing note).
///
/// # Why not the whole message
///
/// The array would become a second copy of every operator paragraph in the
/// tree — hundreds of lines of prose to keep in sync with the source it is
/// supposed to be describing, which is the drift the truncation existed to
/// avoid. The digest gives full-message discrimination at eight characters.
///
/// The cost is real and small: any edit to a message, tail included, changes
/// its key and must be reflected in the ledger. That is the CORRECT event —
/// the gate's own remediation text already says "if a message was REWORDED,
/// update it" — and the failure prints a paste-ready set.
fn message_key(message: &str) -> String {
    let flat = collapse_whitespace(message);
    let prefix: String = flat.chars().take(MESSAGE_KEY_LEN).collect();
    format!("{prefix}#{:08x}", message_digest(&flat))
}

/// A message with every whitespace run collapsed to one space. The one place
/// that normalisation happens, so the key and the collision check cannot
/// disagree about what "the same message" means.
fn collapse_whitespace(message: &str) -> String {
    message.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// FNV-1a 32 over the collapsed message — the discriminating half of a key.
///
/// FNV because the repo already hashes with it (`MessageSchema::schema_hash`)
/// and because the property needed here is only that two DIFFERENT messages
/// almost never agree, over a corpus of tens of sites. Not a security
/// boundary: a ledger entry is written by whoever edits the source.
/// `two_sites_share_a_ledger_key_only_if_they_share_a_message` catches even a
/// genuine collision, so the digest is the mechanism and that arm is the
/// guarantee.
fn message_digest(flat: &str) -> u32 {
    let mut h: u32 = 0x811c_9dc5;
    for b in flat.as_bytes() {
        h ^= u32::from(*b);
        h = h.wrapping_mul(0x0100_0193);
    }
    h
}

