#[test]
fn two_sites_share_a_ledger_key_only_if_they_share_a_message() {
    // THE durable half of the per-site ledger, and the arm that makes a FUTURE
    // collision loud instead of silently widening the hole.
    //
    // The ledger's claim is that a NEW interpolating message cannot be
    // laundered in by retiring another one in the same file. That claim is
    // exactly as strong as the key's ability to tell two messages apart, and
    // for as long as the key was a bare 60-character PREFIX it was not strong
    // enough: `transport/network.rs` carries two DIFFERENT operator paragraphs
    // agreeing for more than that many characters, so they minted ONE key and
    // swapping one for the other moved nothing the multiset could see.
    //
    // A digest closes that BY CONSTRUCTION, which is the mechanism. This is
    // the GUARANTEE, and it is deliberately mechanism-independent: it walks the
    // real tree, groups every site by the key it actually mints, and requires
    // each key to name exactly ONE message. A shorter digest, a reverted
    // prefix, a genuine FNV collision — any of them fails HERE, naming both
    // sites, rather than quietly making the ledger weaker.
    let mut witnesses: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut sites_seen = 0usize;
    for rel in library_src_files() {
        let st = stripped_for(&rel);
        for site in tracing_sites(&st) {
            sites_seen += 1;
            witnesses
                .entry(message_key(&site.message))
                .or_default()
                .entry(collapse_whitespace(&site.message))
                .or_insert_with(|| format!("{rel}:{}", site.line));
        }
    }

    // ANTI-VACUITY: an invariant over an empty walk is satisfied by nothing at
    // all, so the walk must have really found the corpus.
    assert!(
        sites_seen > 100,
        "the walk found only {sites_seen} tracing sites — the invariant below would be \
         vacuous; fix the walk before trusting it"
    );

    let collisions: Vec<String> = witnesses
        .iter()
        .filter(|(_, msgs)| msgs.len() > 1)
        .map(|(key, msgs)| {
            let listed: Vec<String> = msgs
                .iter()
                .map(|(m, at)| {
                    let shown: String = m.chars().take(120).collect();
                    format!("        {at}\n            {shown}")
                })
                .collect();
            format!(
                "    key {key:?} is minted by {} DIFFERENT messages:\n{}",
                msgs.len(),
                listed.join("\n")
            )
        })
        .collect();

    assert!(
        collisions.is_empty(),
        "a ledger key must name exactly ONE message — these name several, so a swap \
         BETWEEN them is invisible to `DECLARED_SITES` and the debt can be laundered:\n{}\n  \
         FIX: strengthen `message_key` (a longer digest, or a longer prefix if the pair \
         merely shares a head). Do NOT reword production text to dodge this.",
        collisions.join("\n")
    );

    // And the SPECIFIC pair this arm was written for must be apart — a general
    // invariant can be satisfied by a walk that stopped finding them.
    let (file, head) = FORMERLY_COLLIDING_PAIR;
    let st = stripped_for(file);
    let pair: Vec<String> = tracing_sites(&st)
        .iter()
        .map(|site| collapse_whitespace(&site.message))
        .filter(|m| m.starts_with(head))
        .collect();
    assert_eq!(
        pair.len(),
        2,
        "{file} no longer carries the two messages sharing the head {head:?} — re-anchor \
         this arm on another pair, or drop it only if no pair shares a 60-char head"
    );
    assert_ne!(
        pair[0], pair[1],
        "the pair must be genuinely DIFFERENT messages"
    );
    assert_ne!(
        message_key(&pair[0]),
        message_key(&pair[1]),
        "the demonstrated collision must be CLOSED: these two paragraphs agree for the \
         whole readable prefix and must still mint different keys"
    );
}

/// The pair that proved the bare-prefix key was too weak: two DIFFERENT
/// operator paragraphs in one file that agree for at least [`MESSAGE_KEY_LEN`]
/// characters. Named, not synthesised, because a synthetic pair proves the
/// helper is injective on inputs someone chose — this pair is what the tree
/// actually ships. The two re-injection failures below share their whole
/// readable head and diverge only in the trailing note telling an operator
/// whether this line is the loud first of a regime or a counted repeat.
const FORMERLY_COLLIDING_PAIR: (&str, &str) = (
    "cerulion_core/src/transport/network.rs",
    "ingress: local publisher mutex poisoned — validated frame dr",
);

#[test]
fn a_site_is_identified_by_its_message_not_by_its_line() {
    // The ledger pins each declared site by message, so the
    // key must survive the things that legitimately change around a message and
    // must not survive a change to the message itself.
    let a = message_key("publisher created for the topic");
    // Re-wrapping a literal across lines (rustfmt does this constantly) is the
    // SAME site — which is exactly why a line number would be the wrong key.
    let b = message_key(
        "publisher   created
     for the topic",
    );
    assert_eq!(
        a, b,
        "whitespace is collapsed, so a re-wrap is not a new site"
    );
    assert_ne!(
        a,
        message_key("publisher destroyed for the topic"),
        "a different message is a different site"
    );
    // THE fix: two messages agreeing for the WHOLE readable prefix still mint
    // different keys. This is the synthetic twin of the real pair in
    // `state_arm_attach.rs`, and it is what a bare-prefix key could not do.
    let shared = "y".repeat(MESSAGE_KEY_LEN);
    let alpha = message_key(&format!("{shared} alpha"));
    let beta = message_key(&format!("{shared} beta"));
    assert_ne!(
        alpha, beta,
        "a key must discriminate on the WHOLE message, not on its first \
         {MESSAGE_KEY_LEN} characters"
    );
    // The prefix is still exactly that long and still READABLE — the digest is
    // a suffix, not a replacement, so `DECLARED_SITES` stays a list a human can
    // read rather than a wall of hex.
    assert!(alpha.starts_with(&shared) && beta.starts_with(&shared));
    let long = "x".repeat(MESSAGE_KEY_LEN + 40);
    let key = message_key(&long);
    assert_eq!(
        key.chars().take(MESSAGE_KEY_LEN).collect::<String>(),
        "x".repeat(MESSAGE_KEY_LEN),
        "the readable half is the first MESSAGE_KEY_LEN characters, verbatim"
    );
    assert_eq!(
        key.chars().count(),
        MESSAGE_KEY_LEN + 9,
        "…plus `#` and eight hex digits, so a key's length is bounded whatever the \
         message's is"
    );
    // Whitespace collapse happens ONCE, before both halves — otherwise a
    // re-wrap would keep the prefix and move the digest, which is the same
    // false-churn a line number would cause.
    assert_eq!(message_key("a  b"), message_key("a\nb"));
}

