const LEVELS: &[&str] = &["trace", "debug", "info", "warn", "error", "event"];

/// `tracing::event!(Level::WARN, ..)` takes the LEVEL as its first argument;
/// the five level macros do not. `event!` is inside the walk because it is the
/// same crate and the same operator surface as the level macros. Left outside,
/// it is invisible to both arms, and the first site written in `event!` form
/// exits the gate silently, while the macro-matcher oracle pins only
/// `log::warn!`'s REJECTION.
const EVENT_MACRO: &str = "event";

#[derive(Debug, PartialEq, Eq)]
enum Placeholder {
    /// `{}` / `{0}` / `{:?}` — a positional splice of a runtime value.
    Positional,
    /// `{name}` — inline capture of a runtime binding.
    Capture,
    /// `{SCREAMING}` — inline capture of a compile-time constant. Allowed.
    Const,
}

#[derive(Debug, PartialEq, Eq, Clone, Copy)]
enum SiteClass {
    Clean,
    /// Prose AND a runtime placeholder.
    Interpolation,
    /// The message is ONLY runtime placeholders.
    PassThrough,
}

struct Site {
    line: usize,
    level: &'static str,
    /// Field names declared BEFORE the message literal (tracing's own grammar:
    /// anything after the message is a format argument, not a field).
    fields: Vec<String>,
    class: SiteClass,
    /// The message literal as written (for the failure message).
    message: String,
    /// The arg in message position is neither a string
    /// literal nor a field — `tracing::warn!(concat!("topic {}", " died"), t)`.
    /// tracing forwards the trailing token tree to `format_args!`, which accepts
    /// `concat!` as its format string, so this is a real interpolating message
    /// that classified `Clean` with an empty message — and the trailing format
    /// ARG was then mis-read as a bare-shorthand FIELD, fabricating a phantom
    /// name into the spelling arm. Reported loudly rather than guessed at.
    non_literal_message: bool,
}

/// Is `code[at..]` the start of a genuine `tracing` level macro invocation?
///
/// Rejects a same-named macro from another path (`log::warn!`), a method call
/// (`.warn!`), and an identifier tail (`my_warn!`), while accepting both the
/// bare imported form (`warn!(`) and any path ending in `tracing::`.
fn is_tracing_macro(code: &str, at: usize, level: &str) -> bool {
    let b = code.as_bytes();
    let end = at + level.len();
    // Must be followed by `!` then optional whitespace then `(`.
    let mut k = end;
    if b.get(k) != Some(&b'!') {
        return false;
    }
    k += 1;
    while k < b.len() && (b[k] as char).is_whitespace() {
        k += 1;
    }
    if b.get(k) != Some(&b'(') {
        return false;
    }
    let before = code[..at].trim_end();
    if before.ends_with("tracing::") {
        return true;
    }
    match before.chars().last() {
        None => true,
        Some(c) if c.is_alphanumeric() || c == '_' || c == ':' || c == '.' => false,
        Some(_) => true,
    }
}

/// Index of the `(` that opens the macro's argument list, given the level start.
fn open_paren(code: &str, at: usize, level: &str) -> usize {
    let b = code.as_bytes();
    let mut k = at + level.len() + 1;
    while b[k] != b'(' {
        k += 1;
    }
    k
}

/// Slice of the balanced argument list, `open` pointing at `(`.
fn balanced_args(code: &str, in_literal: &[bool], open: usize) -> Option<(usize, usize)> {
    let b = code.as_bytes();
    let mut depth = 0usize;
    let mut i = open;
    while i < b.len() {
        if !in_literal[i] {
            match b[i] {
                b'(' | b'[' | b'{' => depth += 1,
                b')' | b']' | b'}' => {
                    depth -= 1;
                    if depth == 0 {
                        return Some((open + 1, i));
                    }
                }
                _ => {}
            }
        }
        i += 1;
    }
    None
}

/// Split the argument list at TOP-LEVEL commas (literals and nested groups are
/// opaque).
fn split_top_level(code: &str, in_literal: &[bool], from: usize, to: usize) -> Vec<(usize, usize)> {
    let b = code.as_bytes();
    let mut out = Vec::new();
    let mut depth = 0usize;
    let mut start = from;
    let mut i = from;
    while i < to {
        if !in_literal[i] {
            match b[i] {
                b'(' | b'[' | b'{' => depth += 1,
                b')' | b']' | b'}' => depth = depth.saturating_sub(1),
                b',' if depth == 0 => {
                    out.push((start, i));
                    start = i + 1;
                }
                _ => {}
            }
        }
        i += 1;
    }
    out.push((start, to));
    out.into_iter()
        .filter(|(a, z)| code[*a..*z].trim() != "")
        .collect()
}

/// Classify the placeholders of a message literal's CONTENT (already unquoted).
fn placeholders(content: &str) -> Vec<Placeholder> {
    let masked = content.replace("{{", "\u{0}").replace("}}", "\u{1}");
    let mut out = Vec::new();
    let bytes = masked.as_bytes();
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes[i] == b'{' {
            if let Some(rel) = masked[i + 1..].find('}') {
                let inner = &masked[i + 1..i + 1 + rel];
                let name = inner.split(':').next().unwrap_or("");
                out.push(
                    if name.is_empty() || name.chars().all(|c| c.is_ascii_digit()) {
                        Placeholder::Positional
                    } else if name.starts_with(|c: char| c.is_ascii_uppercase())
                        && name
                            .chars()
                            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')
                    {
                        Placeholder::Const
                    } else {
                        Placeholder::Capture
                    },
                );
                i = i + 1 + rel + 1;
                continue;
            }
        }
        i += 1;
    }
    out
}

/// The prose of a message literal: everything OUTSIDE its placeholders, with
/// Rust's line-continuation (`\` + newline + indent) folded away.
fn prose(content: &str) -> String {
    let masked = content.replace("{{", "\u{0}").replace("}}", "\u{1}");
    let mut out = String::new();
    let mut rest = masked.as_str();
    while let Some(at) = rest.find('{') {
        out.push_str(&rest[..at]);
        match rest[at + 1..].find('}') {
            Some(rel) => rest = &rest[at + 1 + rel + 1..],
            None => {
                rest = "";
                break;
            }
        }
    }
    out.push_str(rest);
    // A source-level `\<newline>` continuation renders as nothing; anything
    // else that survives is real prose.
    out.replace("\\\n", " ")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace(['\u{0}', '\u{1}'], "")
        .trim()
        .to_string()
}

/// If `arg` starts with a string literal, return its CONTENT (unquoted).
fn leading_string_literal(arg: &str) -> Option<&str> {
    let t = arg.trim_start();
    let b = t.as_bytes();
    // Raw forms first (`r"`, `r#"`, `br#"`).
    let rs = if b.first() == Some(&b'b') && b.get(1) == Some(&b'r') {
        Some(1)
    } else if b.first() == Some(&b'r') {
        Some(0)
    } else {
        None
    };
    if let Some(rs) = rs {
        let mut j = rs + 1;
        while b.get(j) == Some(&b'#') {
            j += 1;
        }
        if b.get(j) == Some(&b'"') {
            let hashes = j - rs - 1;
            let mut k = j + 1;
            while k < b.len() {
                if b[k] == b'"' {
                    let mut h = 0usize;
                    while h < hashes && b.get(k + 1 + h) == Some(&b'#') {
                        h += 1;
                    }
                    if h == hashes {
                        return Some(&t[j + 1..k]);
                    }
                }
                k += 1;
            }
            return Some(&t[j + 1..]);
        }
    }
    if b.first() == Some(&b'"') {
        let mut k = 1usize;
        while k < b.len() {
            match b[k] {
                b'\\' => k += 2,
                b'"' => return Some(&t[1..k]),
                _ => k += 1,
            }
        }
        return Some(&t[1..]);
    }
    None
}

/// A structured-field name declared by `arg`, if any.
///
/// Accepts `name = expr`, the `name` shorthand, and dotted paths (`self.x = ..`
/// is NOT a field name — tracing rejects it — so only bare idents count).
///
/// # The `%`/`?` SHORTHAND is a field declaration too
///
/// `tracing::warn!(?path, "…")` declares a field NAMED `path` (Debug) and
/// `%status` one named `status` (Display) — the sigil chooses the RECORDING
/// STYLE, not whether a field exists. Reading the identifier without stripping
/// it returned `None` for the whole shape, so those fields never reached
/// [`Site::fields`] and the standard-spelling arm would accept `%nodeid` where
/// `node_id=` is the one spelling. The repo really uses this form (`?path` in
/// `cerulion_core/src/trace/bag.rs`, `%reason` in `replay_engine.rs`), so the
/// gap was reachable rather than hypothetical.
///
/// A sigil on the VALUE side (`node_id = %id`) was always read correctly — the
/// identifier there is already leading and the sigil sits after the `=`.
fn field_name(arg: &str) -> Option<String> {
    let t = arg.trim();
    if t.starts_with("target:") || t.starts_with("parent:") || t.starts_with("name:") {
        return None;
    }
    let t = t
        .strip_prefix('%')
        .or_else(|| t.strip_prefix('?'))
        .unwrap_or(t)
        .trim_start();
    // A RAW IDENTIFIER field (`r#type = %ty`). tracing records the field under
    // `type`; the `r#` is Rust syntax for using a keyword as an identifier, not
    // part of the name. Without this the whole site was unreadable — `r#type`
    // parsed as the identifier `r` followed by `#type`, which is neither a
    // field nor a message, so the site tripped the non-literal-message report.
    // Found by running the walk against the real tree: `rmw_cerulion`'s
    // `decode_failure_latch` and `api/misc.rs` use the form.
    let t = match t.strip_prefix("r#") {
        Some(rest) if rest.starts_with(|c: char| c.is_alphabetic() || c == '_') => rest,
        _ => t,
    };
    let ident_end = t
        .find(|c: char| !(c.is_alphanumeric() || c == '_'))
        .unwrap_or(t.len());
    if ident_end == 0 {
        return None;
    }
    let ident = &t[..ident_end];
    if !ident.starts_with(|c: char| c.is_alphabetic() || c == '_') {
        return None;
    }
    let rest = t[ident_end..].trim_start();
    if rest.is_empty() {
        return Some(ident.to_string()); // shorthand `field,`
    }
    if let Some(after) = rest.strip_prefix('=') {
        if !after.starts_with('=') {
            return Some(ident.to_string());
        }
    }
    None
}

/// Every `const NAME` / `static NAME` declared anywhere in the walked library
/// sources, as a set of identifiers.
///
/// # Why the classifier needs this
///
/// [`placeholders`] exempts an ALL-CAPS capture as a compile-time constant, on
/// the sound reasoning that `{SCREAMING_CONST}` renders at compile time and so
/// interpolates no runtime value. But it read only the CASING, and casing is a
/// convention rather than a fact — nothing stopped `let TOPIC = value;` +
/// `warn!("{TOPIC}")` from walking straight through the arm.
///
/// # Scope: the direct bypass cannot ship
///
/// That exact bypass cannot ship: `non_snake_case` is warn-by-default and CI
/// runs `cargo clippy --workspace --all-targets -- -D warnings`, which turns it
/// into a hard error (MEASURED — `rustc -D warnings` on `let TOPIC = "abc";`
/// reports "variable `TOPIC` should have a snake case name"). So the guard here
/// is defence in depth against the shapes rustc does NOT reject: an explicit
/// `#[allow(non_snake_case)]`, and any future capture whose casing says
/// "constant" while its declaration says otherwise.
///
/// The set is the UNION over every walked file rather than per-file, because a
/// const is routinely `use`d across modules and a per-file check would flag a
/// legitimate import. BOTH residuals of that choice are stated rather than
/// hidden, and they point opposite ways:
///
/// * A const imported from an EXTERNAL crate is declared nowhere in this tree,
///   so a capture of one reads as unverified and fails LOUDLY — the safe
///   direction, and the remedy is the same as for any other flagged message
///   (lift it into a field, or give the value a local `const`).
/// * A name is matched, never RESOLVED. A `#[allow(non_snake_case)] let TOPIC`
///   that happens to share its spelling with a real const somewhere else in the
///   tree is exempted — the union cannot tell the two apart. That is the
///   unsafe direction, and it is bounded by needing a deliberate `#[allow]`
///   (rustc's `non_snake_case` is warn-by-default and CI runs
///   `-D warnings`) plus a spelling collision with a genuine declaration.
///   Resolving scopes is a borrow-checker's job, not a walk's.
fn declared_const_names() -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for rel in library_src_files() {
        let st = stripped_for(&rel);
        let code = &st.code;
        for kw in ["const ", "static "] {
            let mut from = 0usize;
            while let Some(rel_at) = code[from..].find(kw) {
                let at = from + rel_at;
                from = at + kw.len();
                // Inside a STRING LITERAL this is not a declaration, it is
                // TEXT. `code_only` keeps literals on purpose (the message is
                // the evidence), so the mask is what separates the two — and
                // without it `codegen/generator/structs.rs`, which EMITS
                // `const NS_PER_SEC: u64 = ..` as text into a generated file,
                // donated `NS_PER_SEC` to the accepted set. A `{NS_PER_SEC}`
                // capture would then have been exempted on evidence that is a
                // quoted string in a code generator. The macro scanner already
                // refuses to match inside the mask for the mirror-image reason;
                // this walk was the half that did not.
                if st.in_literal.get(at).copied().unwrap_or(false) {
                    continue;
                }
                // The keyword must start a token (not the tail of an ident).
                if at > 0 {
                    let prev = code[..at].chars().next_back().unwrap_or(' ');
                    if prev.is_alphanumeric() || prev == '_' {
                        continue;
                    }
                }
                let rest = code[from..].trim_start();
                // `static mut NAME` — step over the `mut`.
                let rest = rest
                    .strip_prefix("mut ")
                    .map(str::trim_start)
                    .unwrap_or(rest);
                let end = rest
                    .find(|c: char| !(c.is_alphanumeric() || c == '_'))
                    .unwrap_or(rest.len());
                if end == 0 {
                    continue;
                }
                let ident = &rest[..end];
                // A `static` with interior mutability is not
                // a compile-time constant in any sense the exemption relies on —
                // `static LAST_TOPIC: RwLock<String>` or an `AtomicU64` rendered
                // as `{X:?}` puts per-message runtime data into the message text
                // while the casing rule says "fixed at compile time". Such a
                // declaration does not join the accepted set, so a capture of one
                // is reported like any other runtime value.
                // Bound the "type" to THIS declaration. Reading `rest[end..]`
                // took the rest of the FILE, so one `AtomicU64` anywhere in a
                // module excluded every const in it — which is how this arm
                // first failed on `HELD_HEAD_WARN_BOUNDARIES`.
                let tail = &rest[end..];
                let decl_end = tail.find(';').unwrap_or(tail.len());
                let line_end = tail.find('\n').unwrap_or(tail.len());
                let ty = &tail[..decl_end.min(line_end)];
                let interior_mutable = [
                    "Atomic", "Mutex", "RwLock", "Cell", "OnceLock", "LazyLock", "OnceCell",
                ]
                .iter()
                .any(|m| ty.contains(m));
                if ident.starts_with(|c: char| c.is_alphabetic() || c == '_') && !interior_mutable {
                    out.insert(ident.to_string());
                }
            }
        }
    }
    out
}

/// The ALL-CAPS captures in `content` that resolve to no declared
/// `const`/`static` — i.e. the ones [`placeholders`] exempted on CASING alone
/// and that nothing in the tree backs up. `_` is skipped: `{_}` is not a
/// capture rustc would accept, and a lone underscore names nothing.
fn unverified_const_captures(content: &str, declared: &BTreeSet<String>) -> Vec<String> {
    let mut out = Vec::new();
    let masked = content.replace("{{", "\u{0}").replace("}}", "\u{1}");
    let bytes = masked.as_bytes();
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes[i] == b'{' {
            if let Some(rel) = masked[i + 1..].find('}') {
                let inner = &masked[i + 1..i + 1 + rel];
                let name = inner.split(':').next().unwrap_or("");
                let is_const = name.starts_with(|c: char| c.is_ascii_uppercase())
                    && name
                        .chars()
                        .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
                if is_const && !declared.contains(name) && !out.iter().any(|n| n == name) {
                    out.push(name.to_string());
                }
                i = i + 1 + rel + 1;
                continue;
            }
        }
        i += 1;
    }
    out
}

/// Every tracing call site in one already-stripped file.
fn tracing_sites(st: &Stripped) -> Vec<Site> {
    let code = &st.code;
    let mut sites = Vec::new();
    for level in LEVELS {
        let mut from = 0usize;
        while let Some(rel) = code[from..].find(level) {
            let at = from + rel;
            from = at + level.len();
            if st.in_literal[at] || !is_tracing_macro(code, at, level) {
                continue;
            }
            let open = open_paren(code, at, level);
            let Some((a, z)) = balanced_args(code, &st.in_literal, open) else {
                continue;
            };
            let mut args = split_top_level(code, &st.in_literal, a, z);
            // `event!`'s first argument is the LEVEL, not a field.
            if *level == EVENT_MACRO && !args.is_empty() {
                args.remove(0);
            }
            let mut fields = Vec::new();
            let mut class = SiteClass::Clean;
            let mut message = String::new();
            let mut non_literal_message = false;
            for (s, e) in args {
                let arg = &code[s..e];
                // Neither a literal nor a field: this IS the message position,
                // holding something the walk cannot read (see `non_literal_message`).
                //
                // TWO shapes are excluded, both found by running this against the
                // real tree rather than reasoned about:
                //
                // * tracing's own DIRECTIVES (`target:`, `parent:`, `name:`) are
                //   not fields and not messages — `field_name` returns `None` for
                //   them BY DESIGN, so treating that `None` as "unreadable
                //   message" broke `trace!(target: "iceoryx2", origin = %o, "msg")`
                //   and lost the real field behind it.
                // * a macro_rules METAVARIABLE (`$loud`, `$($extra)*`). The three
                //   hits this produced in `codegen/unknown_hash.rs` are a
                //   `macro_rules!` TEMPLATE, not call sites; what actually runs is
                //   the expansion. A template is a genuine blind spot of a source
                //   walk, and it is a different one from the `concat!` class this
                //   flag exists for — flagging it would be a false positive on
                //   code that is not a violation.
                let t = arg.trim();
                let directive =
                    t.starts_with("target:") || t.starts_with("parent:") || t.starts_with("name:");
                let metavariable = t.starts_with('$');
                if !directive
                    && !metavariable
                    && leading_string_literal(arg).is_none()
                    && field_name(arg).is_none()
                {
                    non_literal_message = true;
                    break;
                }
                if let Some(content) = leading_string_literal(arg) {
                    // Skip `field = "value"` — a string-VALUED field, not the
                    // message. `field_name` already told us if this is a field.
                    if field_name(arg).is_none() {
                        let phs = placeholders(content);
                        let runtime = phs.iter().any(|p| *p != Placeholder::Const);
                        if runtime {
                            // PassThrough is EXACTLY one placeholder and no
                            // prose — a message that IS a forwarded value.
                            // `"{} {}"` has no prose either, but it splices TWO
                            // values together, which is interpolation with the
                            // connective tissue removed.
                            class = if phs.len() == 1 && prose(content).is_empty() {
                                SiteClass::PassThrough
                            } else {
                                SiteClass::Interpolation
                            };
                        }
                        message = content.replace('\n', " ");
                        break; // fields only precede the message
                    }
                }
                if let Some(f) = field_name(arg) {
                    fields.push(f);
                }
            }
            sites.push(Site {
                line: code[..at].matches('\n').count() + 1,
                level,
                fields,
                class,
                message,
                non_literal_message,
            });
        }
    }
    sites.sort_by_key(|s| s.line);
    sites
}

// ---------------------------------------------------------------------------
// The walk
