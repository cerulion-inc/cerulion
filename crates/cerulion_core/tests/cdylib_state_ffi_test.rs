/// A sink that reports whether the HOST latched it, so "was `refuse()` called"
/// is observable through the production `StateSink` API rather than inferred
/// from a re-implementation of `BoundedSink`'s accounting.
///
/// One type serves both halves of the discrimination: `panic_at` makes it
/// unwind on the n-th write (a BROKEN sink), `cap` makes it fill (an EXHAUSTED
/// one). The two must be charged differently, and nothing but this counter can
/// tell them apart from outside.
struct LatchSpySink {
    cap: usize,
    panic_at: Option<usize>,
    writes: usize,
    accepted: usize,
    returned_full: bool,
    refuse_calls: usize,
}

impl LatchSpySink {
    fn panicking(panic_at: usize) -> Self {
        Self {
            // Ample: this sink must be observably NOT full when it unwinds, or
            // the arm could not tell the two conditions apart.
            cap: usize::MAX,
            panic_at: Some(panic_at),
            writes: 0,
            accepted: 0,
            returned_full: false,
            refuse_calls: 0,
        }
    }

    fn bounded(cap: usize) -> Self {
        Self {
            cap,
            panic_at: None,
            writes: 0,
            accepted: 0,
            returned_full: false,
            refuse_calls: 0,
        }
    }
}

impl cerulion_core::state::StateSink for LatchSpySink {
    fn write(&mut self, bytes: &[u8]) -> Result<(), cerulion_core::state::SinkFull> {
        self.writes += 1;
        if self.panic_at == Some(self.writes) {
            panic!("this host sink is broken");
        }
        if self.returned_full || self.accepted + bytes.len() > self.cap {
            self.returned_full = true;
            return Err(cerulion_core::state::SinkFull);
        }
        self.accepted += bytes.len();
        Ok(())
    }

    fn refuse(&mut self) {
        self.refuse_calls += 1;
    }
}

#[test]
#[serial]
fn a_sink_that_unwound_is_not_latched_as_a_sink_that_filled() {
    // Driven through the MACRO fixture, so the exporter under test is the
    // GENERATED one — and the generated `__CerFfiStateSink::write` maps EVERY
    // non-zero callback return onto `SinkFull`, panic included. The cdylib
    // therefore reports -6 ("the host sink refused") for a sink that did not
    // refuse anything; only the host's own bridge knows it unwound.
    let (_runtime, probe, _seen) = built_probe("latchpanic");

    let mut sink = LatchSpySink::panicking(1);
    let err = probe
        .lock()
        .expect("probe")
        .capture_state(&mut sink)
        .expect_err("a capture whose sink unwound is not a capture");

    // The apparatus really produced the condition: the sink unwound, and it was
    // NOT full — it never once returned `SinkFull`, and its capacity is
    // unbounded. Without this the pin below could pass on a sink that simply
    // never got far enough to fill.
    assert_eq!(sink.writes, 1, "it unwound on its first write");
    assert!(
        !sink.returned_full,
        "and never reported itself full — the two conditions are disjoint here"
    );

    // THE PIN. `refuse()` means "this sink is exhausted": it latches the sink
    // and, on a `BoundedSink`, charges the boundary budget its ENTIRE capacity
    // instead of the bytes written. A sink that unwound is not exhausted, it is
    // BROKEN — the opposite diagnosis, which is why the bridge tracks `full`
    // and `panicked` separately in the first place. Charging it as exhaustion
    // spends a budget nobody used and presents a broken caller sink to the
    // carrier as an arena too small. The in-process `walk_inline` agrees: its
    // `CaptureUnwound` arm charges `sink.consumed()` and never calls `refuse`.
    assert_eq!(
        sink.refuse_calls, 0,
        "a panicked sink must not be latched as exhausted"
    );

    // And the diagnosis still names the panic rather than the buffer.
    let text = err.to_string();
    assert!(
        text.contains("panicked"),
        "a broken sink and a small buffer are opposite diagnoses: {text}"
    );
}

