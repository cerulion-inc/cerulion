/// A sink that records EVERY chunk it was offered — including the ones it
/// refused — so a test can tell "the exporter stopped" from "the exporter kept
/// going". `BoundedSink` cannot: a refused write leaves no trace of its size.
struct RecordingSink {
    cap: usize,
    accepted: Vec<u8>,
    /// One entry per `write` call: the chunk's length and whether it was taken.
    offers: Vec<(usize, bool)>,
    refused: bool,
}

impl RecordingSink {
    fn new(cap: usize) -> Self {
        Self {
            cap,
            accepted: Vec::new(),
            offers: Vec::new(),
            refused: false,
        }
    }
}

impl cerulion_core::state::StateSink for RecordingSink {
    fn write(&mut self, bytes: &[u8]) -> Result<(), cerulion_core::state::SinkFull> {
        // Latches exactly like `BoundedSink`: a small write landing after a
        // refused large one would leave a hole in the middle of an encoding
        // that still looks structurally valid.
        if self.refused || self.accepted.len() + bytes.len() > self.cap {
            self.offers.push((bytes.len(), false));
            self.refused = true;
            return Err(cerulion_core::state::SinkFull);
        }
        self.accepted.extend_from_slice(bytes);
        self.offers.push((bytes.len(), true));
        Ok(())
    }

    fn refuse(&mut self) {
        self.refused = true;
    }
}

/// A sink that UNWINDS on its first write — the other way a host sink can fail
/// a chunk. The trampoline catches it (an `extern "C"` unwind would abort the
/// process), so the cdylib sees only a non-zero return, exactly as for a
/// refusal.
struct PanickingSink {
    calls: usize,
}

impl cerulion_core::state::StateSink for PanickingSink {
    fn write(&mut self, _bytes: &[u8]) -> Result<(), cerulion_core::state::SinkFull> {
        self.calls += 1;
        panic!("this host sink is broken");
    }
}

