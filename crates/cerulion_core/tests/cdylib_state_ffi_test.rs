#[test]
#[serial]
fn a_symbol_less_cdylib_declares_no_state_and_refuses_a_restore_naming_the_node_and_the_fix() {
    // The raw-FFI fixture: a real, hand-written cdylib that loads fine and
    // exports none of the three state symbols.
    let mut entry = DylibNodeEntry::load(&symbol_less_cdylib())
        .expect("a symbol-less cdylib must still LOAD (the exports are additive)");

    // (a) It declares NO state, so `restore_node_states` reports it under
    //     `declared_no_state` instead of applying anything.
    assert_eq!(entry.state_shape(), None);

    // (b) And reaching the restore path directly REFUSES. Never `Ok(())`: that
    //     would leave the node at its constructor's `Default` while the caller
    //     recorded it as restored.
    let err = entry
        .restore_state(&hand_payload(1, "x", &[], &[]))
        .expect_err("an uncovered cdylib must refuse a recorded anchor");
    let text = err.to_string();
    assert!(
        text.contains("declares no restorable state"),
        "names the condition: {text}"
    );
    assert!(
        text.contains("test_node_cdylib"),
        "names the offending node: {text}"
    );
    assert!(
        text.contains("cerulion_node_restore_state") && text.contains("#[cerulion_node]"),
        "names the fix: {text}"
    );
    assert!(
        text.contains("resume from its constructor's defaults"),
        "says what silence would have cost: {text}"
    );

    // (c) The capture half refuses too — an anchor that captured nothing is
    //     worse than no anchor, because a resume would apply that emptiness.
    let mut sink = VecSink::new();
    let err = entry
        .capture_state(&mut sink)
        .expect_err("an uncovered cdylib must refuse to capture");
    assert!(
        err.to_string().contains("declares no capturable state"),
        "names the condition: {err}"
    );
    assert!(sink.is_empty(), "and wrote nothing");
}

#[test]
#[serial]
fn an_uninitialized_cdylib_still_declares_its_shape_but_refuses_to_capture_or_restore() {
    // The shape is a const of the TYPE, so it is answerable before `init()` —
    // which is what stops a not-yet-initialized node from claiming it has no
    // state and being skipped by the restore.
    let mut entry = DylibNodeEntry::load(&state_cdylib()).expect("state cdylib loads");
    assert_eq!(
        entry.state_shape(),
        Some(<twin::StateProbeNode as CerulionState>::STATE_SHAPE),
        "the shape is readable at load, with no handle and no init"
    );

    let mut sink = VecSink::new();
    let err = entry
        .capture_state(&mut sink)
        .expect_err("no instance exists yet");
    assert!(
        err.to_string().contains("has not been initialized"),
        "{err}"
    );

    let err = entry
        .restore_state(&hand_payload(1, "", &[], &[]))
        .expect_err("no instance exists yet");
    assert!(
        err.to_string().contains("has not been initialized"),
        "{err}"
    );
}

