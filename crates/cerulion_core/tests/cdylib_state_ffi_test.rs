#[test]
#[serial]
fn a_tick_logic_edit_keeps_the_shape_while_a_field_retype_moves_it() {
    let entry = DylibNodeEntry::load(&state_cdylib()).expect("state cdylib loads");
    let cdylib_shape = entry.state_shape().expect("declares a shape");

    // Read through the production `NodeEntry` seam on both twins, not off the
    // associated const: the const is what the seam RETURNS, and a test that
    // reads it directly cannot see a seam that stopped returning it.
    let twin_shape = twin::StateProbeNodeEntry::new()
        .state_shape()
        .expect("the twin declares a shape");
    let skewed_shape = skewed::StateProbeNodeEntry::new()
        .state_shape()
        .expect("the skewed twin declares a shape");

    // Same struct, DIFFERENT tick body → same shape. A recording keeps
    // restoring across a logic edit.
    assert_eq!(
        cdylib_shape, twin_shape,
        "a tick-logic edit is not a shape edit"
    );

    // One field RETYPED → a different shape, so the anchor is invalidated.
    assert_ne!(
        cdylib_shape, skewed_shape,
        "retyping `counter` u64 -> u32 must move the shape"
    );
}

#[test]
#[serial]
