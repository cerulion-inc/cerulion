// ===========================================================================
// THE MISREPORTING-EXPORTER PIN: a return code is a CLAIM, not the verdict
// ===========================================================================
//
// The three state symbols are ADDITIVE and resolved BY NAME, so nothing tells the
// host that the exporter behind them came out of `#[cerulion_node]`. The
// generated one maps a refused chunk onto `-6`; a HAND-WRITTEN raw-FFI one (the
// population `test_node_cdylib` next door already proves exists) is free to
// ignore the callback's non-zero return, keep streaming, and still report 0.
//
// If the host believes that 0, it accepts whatever prefix its own sink managed
// to take as this node's WHOLE state. A truncated anchor is not a loud failure:
// it is a recording that restores later as if it were complete, so the resumed
// node runs on state nobody captured while the run reports it `restored`
// (Principle #6 — a missing frame must not be lost silently; Principle #13 —
// nothing fabricated).
//
// These arms drive the real misbehaviour over a real `dlopen`
// (`test_node_state_liar_cdylib`), because every macro fixture in the tree is
// incapable of producing it by construction.

/// This fixture's declared `STATE_SHAPE`, spelled out by hand — the same
/// literal the fixture declares, written independently here so the assertion is
/// a cross-check rather than a read-back.
const LIAR_SHAPE: u64 = 0x1053_D600_5A1E_0001;

/// The liar fixture's documented payload: `counter` LE, then the label, then
/// the tail marker. Hand-built from the fixture's own module table.
fn liar_payload(counter: u64) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(&counter.to_le_bytes());
    out.extend_from_slice(b"liar_fixture");
    out.extend_from_slice(&0xDEAD_BEEFu32.to_le_bytes());
    out
}

/// The hand-written raw-FFI cdylib whose exporter can be told to lie.
fn liar_cdylib() -> std::path::PathBuf {
    find_cdylib("test_node_state_liar_cdylib")
}

