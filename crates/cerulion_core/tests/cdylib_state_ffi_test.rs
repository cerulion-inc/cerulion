/// A twin of the cdylib fixture's struct, declared field-for-field and NAMED
/// identically (the shape folds the type name, so a differently-named twin
/// would prove nothing).
///
/// Its `tick` body is DELIBERATELY different from the fixture's. That is the
/// shape contract's first half made testable: a tick-logic edit is not a shape
/// edit, so a recording keeps restoring across one.
mod twin {
    use std::collections::HashMap;

    use cerulion_core::prelude::*;
    use native_ros2_messages::geometry_msgs::Quaternion;

    #[cerulion_node(period_ms = 10)]
    pub struct StateProbeNode {
        #[output]
        pub out: Quaternion,
        pub counter: u64,
        pub label: String,
        pub history: Vec<f64>,
        pub tags: HashMap<u32, u8>,
        #[cerulion(reconstruct)]
        pub handle: u64,
    }

    #[cerulion_node_impl]
    impl StateProbeNode {
        fn tick(&mut self) -> Result<(), NodeError> {
            // Deliberately NOT the fixture's body: different arithmetic, same
            // fields. The shape must not notice.
            self.out.x = (self.counter * 2) as f64;
            self.out.y = self.history.iter().sum::<f64>();
            self.out.z = self.label.len() as f64;
            self.out.w = (self.handle + self.tags.len() as u64) as f64;
            self.counter += 3;
            Ok(())
        }
    }
}

/// The same struct with ONE field RETYPED (`counter: u64` → `u32`).
///
/// The shape contract's second half: a struct-shape edit invalidates the anchor,
/// and it must be refused rather than decoded as a prefix.
mod skewed {
    use std::collections::HashMap;

    use cerulion_core::prelude::*;
    use native_ros2_messages::geometry_msgs::Quaternion;

    #[cerulion_node(period_ms = 10)]
    pub struct StateProbeNode {
        #[output]
        pub out: Quaternion,
        pub counter: u32,
        pub label: String,
        pub history: Vec<f64>,
        pub tags: HashMap<u32, u8>,
        #[cerulion(reconstruct)]
        pub handle: u64,
    }

    #[cerulion_node_impl]
    impl StateProbeNode {
        fn tick(&mut self) -> Result<(), NodeError> {
            self.out.x = self.counter as f64;
            self.out.y = self.history.len() as f64;
            self.out.z = self.label.len() as f64;
            self.out.w = (self.handle + self.tags.len() as u64) as f64;
            self.counter += 1;
            Ok(())
        }
    }
}

