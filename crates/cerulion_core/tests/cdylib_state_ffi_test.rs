/// The documented encoding of the fixture's three CAPTURED fields, in
/// declaration order. Written out by hand rather than produced by the encoder,
/// so an assertion against it is a cross-check and not a self-compare.
fn hand_payload(counter: u64, label: &str, history: &[f64], tags: &[(u32, u8)]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(&counter.to_le_bytes());
    out.extend_from_slice(&(label.len() as u32).to_le_bytes());
    out.extend_from_slice(label.as_bytes());
    out.extend_from_slice(&(history.len() as u32).to_le_bytes());
    for f in history {
        out.extend_from_slice(&f.to_le_bytes());
    }
    // A hash-like container emits in SORTED key order, so a `HashMap`'s
    // per-process iteration order never reaches a recording. `tags` is passed
    // already sorted; the oracle does not sort it, so a capture that emitted in
    // iteration order would have to be lucky to pass.
    out.extend_from_slice(&(tags.len() as u32).to_le_bytes());
    for (k, v) in tags {
        out.extend_from_slice(&k.to_le_bytes());
        out.extend_from_slice(&v.to_le_bytes());
    }
    out
}

/// The bytes of everything BEFORE the hash-like field, which is where a capture
/// into a too-small sink must stop when the bound crossed the FFI.
fn hand_payload_before_tags(counter: u64, label: &str, history: &[f64]) -> Vec<u8> {
    let full = hand_payload(counter, label, history, &[]);
    full[..full.len() - 4].to_vec()
}

/// Frame a payload the way a recorded anchor is framed. The FRAMING comes from
/// production code (`AnchorBlob::write_header`) because that is the half the
/// runtime decodes; only the payload is hand-built.
fn framed(shape: u64, payload: &[u8]) -> Vec<u8> {
    let mut sink = VecSink::new();
    AnchorBlob::write_header(shape, &mut sink).expect("framing fits a Vec");
    let mut blob = sink.into_inner();
    blob.extend_from_slice(payload);
    blob
}

