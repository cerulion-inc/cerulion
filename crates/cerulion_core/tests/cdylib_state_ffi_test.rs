// ===========================================================================
// THE PANIC-CONTAINMENT PIN (a broken encoder must not brick the library)
// ===========================================================================

/// The macro cdylib whose hand-written `CerulionState` field impl can be told
/// to panic.
fn panic_cdylib() -> std::path::PathBuf {
    find_cdylib("test_node_state_panic_cdylib")
}

/// Two INDEPENDENT nodes from the one panic fixture, both `init`'d.
///
/// Two, because the blast radius is the whole point: `NODES` is a per-CDYLIB
/// registry, so a panic that unwinds through its guard poisons it for every
/// node the library ever loaded — not just the one that panicked. A one-node
/// harness cannot tell "this capture failed" from "this library is dead".
fn two_panic_nodes() -> (DylibNodeEntry, DylibNodeEntry) {
    let mut a = DylibNodeEntry::load(&panic_cdylib()).expect("the panic cdylib loads");
    let mut b = DylibNodeEntry::load(&panic_cdylib()).expect("the panic cdylib loads twice");
    for entry in [&mut a, &mut b] {
        entry
            .init(cerulion_core::graph::node::NodeContext::for_tests(
                IndexMap::new(),
                IndexMap::new(),
            ))
            .expect("the panic fixture inits");
    }
    (a, b)
}

#[test]
#[serial]
fn a_panicking_state_encoder_fails_its_own_capture_without_poisoning_the_cdylibs_node_registry() {
    let (a, b) = two_panic_nodes();

    // The CONTROL first, so every number below is attributable to the panic
    // rather than to the fixture: with the mode off, both nodes capture the
    // hand-built encoding of `Fragile` — a bare `u64`, value 0.
    let mut sink = VecSink::new();
    a.capture_state(&mut sink).expect("a healthy capture");
    assert_eq!(sink.into_inner(), 0u64.to_le_bytes().to_vec());

    let refusal = {
        let _panic = EnvGuard::set("STATE_PANIC_MODE", "capture");
        let mut sink = VecSink::new();
        let err = a
            .capture_state(&mut sink)
            .expect_err("a panicking encoder cannot report success");
        assert!(
            sink.is_empty(),
            "and nothing was captured — a partial encoding is not an anchor"
        );
        err.to_string()
    };

    // THE PIN, asserted BEFORE the wording below: a message assertion that
    // fires first would shadow this one, and this is the claim that matters. `cer_capture` ran while the export held this cdylib's `NODES`
    // MutexGuard. An unwind through that guard POISONS it, and `NODES` is
    // per-library: from that moment every capture, restore, tick and shutdown
    // of every node loaded from this cdylib fails "NODES mutex poisoned", for
    // the life of the process, with the cause misreported as a tick panic that
    // never happened. So the second node — which never captured
    // anything and was nowhere near the panic — is the witness.
    b.capture_state(&mut VecSink::new())
        .expect("the OTHER node must be untouched by a panic in the first");

    // Only now the wording, which is a separate claim, caught separately:
    // the OUTER `catch_unwind` also returns -4, so a host that reported its
    // generic "panic caught by catch_unwind" would pass every assertion above.
    assert!(
        refusal.contains("encoder panicked"),
        "names what happened, not merely that something did: {refusal}"
    );

    // And the node that panicked is not itself dead: it captures again as soon
    // as its encoder does.
    let mut sink = VecSink::new();
    a.capture_state(&mut sink).expect("the same node recovers");
    assert_eq!(sink.into_inner(), 0u64.to_le_bytes().to_vec());
}

#[test]
#[serial]
fn a_panicking_state_decoder_fails_its_own_restore_without_poisoning_the_cdylibs_node_registry() {
    let (mut a, mut b) = two_panic_nodes();
    // The single captured field encodes as a bare `u64`, so the whole payload
    // for this node is eight bytes — hand-built, per the documented encoding.
    let payload = 42u64.to_le_bytes().to_vec();

    // CONTROL: the restore lands, and is observable through the node's own tick
    // (which publishes `payload.value` and then increments it).
    a.restore_state(&payload).expect("a healthy restore");

    let refusal = {
        let _panic = EnvGuard::set("STATE_PANIC_MODE", "restore");
        a.restore_state(&payload)
            .expect_err("a panicking decoder cannot report success")
            .to_string()
    };

    // The same no-poison pin on the restore half, and again BEFORE the wording: the
    // sibling node, which never restored anything, is the witness.
    b.restore_state(&payload)
        .expect("the OTHER node must be untouched by a panic in the first");

    assert!(
        refusal.contains("decoder panicked"),
        "names what happened, not merely that something did: {refusal}"
    );
    assert!(
        refusal.contains("PARTIALLY restored"),
        "and says the run must fail rather than continue: {refusal}"
    );
    a.restore_state(&payload)
        .expect("and the node that panicked recovers");
}

