//! Checkpoint state capture and restore across the cdylib
//! wall, driven over a real `dlopen` through `DylibNodeEntry`.
//!
//! # What this guards against
//!
//! Every `#[cerulion_node]` struct carries an `impl CerulionState`
//! and the runtime has a restore seam — but the two must be joined for
//! the SHIPPING node form. A `graph run` loads cdylibs; if `DylibNodeEntry`
//! inherited `NodeEntry`'s defaults, every cdylib node would declare **no**
//! restorable state and `restore_node_states` would skip it: a recorded anchor
//! offered and silently dropped, the node resuming from its constructor.
//!
//! # What is asserted here, and against what
//!
//! Every payload oracle is **hand-built from the documented encoding** (see
//! `cerulion_core::state`'s module table) — never a re-capture compared with
//! itself:
//!
//! | field | bytes |
//! |---|---|
//! | `counter: u64` | 8 LE |
//! | `label: String` | `u32` LE byte length + UTF-8 |
//! | `history: Vec<f64>` | `u32` LE count + each `f64`'s LE bit pattern |
//! | `tags: HashMap<u32, u8>` | `u32` LE count + sorted `(key, value)` pairs |
//! | `handle: u64` (`#[cerulion(reconstruct)]`) | **none** |
//!
//! The `#[output]` port contributes nothing, and that is asserted rather than
//! assumed: a walk that included it would not compile at all, but a walk that
//! included the ESCAPED field would compile and quietly clobber a handle the
//! node re-derived in `init()`.
//!
//! # The refuse-on-uncovered pin
//!
//! A cdylib WITHOUT the exports — every hand-written raw-FFI node, every older
//! build — must REFUSE at the restore path naming the node and the fix. It must
//! never report success while leaving the node at `Default`, because a resumed
//! run would then produce a confident divergence report about an execution that
//! never happened. Pinned by
//! `a_symbol_less_cdylib_declares_no_state_and_refuses_a_restore_naming_the_node_and_the_fix`
//! over the real raw-FFI `test_node_cdylib`.
//!
//! # The misreporting-exporter pin (a return code is a CLAIM, not the verdict)
//!
//! The three state symbols are ADDITIVE and resolved BY NAME, so nothing tells the
//! host that the exporter behind them was generated by `#[cerulion_node]`. A
//! hand-written raw-FFI exporter may ignore the sink callback's non-zero
//! return, keep streaming, and still report 0 — and a host that believes that 0
//! accepts whatever prefix its own sink took as the node's WHOLE state. Pinned
//! by the `..._even_though_the_cdylib_reported_success` pair over
//! `test_node_state_liar_cdylib`, a real hand-written cdylib built for exactly
//! this: no macro fixture can reproduce it, because the generated exporter is
//! correct by construction.
//!
//! # Running (cdylib `NODES` singleton + iceoryx2 SHM → serial)
//!
//! ```bash
//! cargo build -p test_node_macro_state_cdylib -p test_node_cdylib \
//!             -p test_node_state_liar_cdylib
//! cargo test -p cerulion_core --test cdylib_state_ffi_test -- --test-threads=1
//! ```

