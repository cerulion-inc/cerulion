#[test]
#[serial]
fn a_hand_built_anchor_restores_and_re_captures_byte_identical() {
    let (_runtime, probe, _seen) = built_probe("rt");

    let want = hand_payload(100, "resumed-state", &[1.5, 2.5, 3.5], &[(1, 10), (2, 20)]);
    probe
        .lock()
        .expect("probe")
        .restore_state(&want)
        .expect("a hand-built payload restores");

    let mut sink = VecSink::new();
    probe
        .lock()
        .expect("probe")
        .capture_state(&mut sink)
        .expect("re-capture");
    // Byte-identical to what went IN — the round trip closes on the hand
    // oracle at both ends, so neither half is compared against itself.
    assert_eq!(sink.into_inner(), want);
}

