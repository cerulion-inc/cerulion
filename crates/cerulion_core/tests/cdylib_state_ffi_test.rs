/// Where cargo put the fixture cdylibs.
///
/// Honours `CARGO_TARGET_DIR` before falling back to `<workspace>/target`: the
/// sibling cdylib tests hardcode the latter, which silently stops finding
/// fixtures the moment anyone builds with a shared target directory.
fn target_dir() -> std::path::PathBuf {
    if let Ok(dir) = std::env::var("CARGO_TARGET_DIR") {
        if !dir.is_empty() {
            return std::path::PathBuf::from(dir);
        }
    }
    let mut path = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    path.pop(); // up from crates/cerulion_core to crates/
    path.pop(); // up from crates/ to the workspace root
    path.push("target");
    path
}

fn find_cdylib(crate_name: &str) -> std::path::PathBuf {
    let mut path = target_dir();
    path.push("debug");
    #[cfg(target_os = "macos")]
    path.push(format!("lib{crate_name}.dylib"));
    #[cfg(target_os = "linux")]
    path.push(format!("lib{crate_name}.so"));
    #[cfg(target_os = "windows")]
    path.push(format!("{crate_name}.dll"));
    assert!(
        path.exists(),
        "test cdylib not found at {path:?}. Run `cargo build -p {crate_name}` first."
    );
    path
}

fn state_cdylib() -> std::path::PathBuf {
    find_cdylib("test_node_macro_state_cdylib")
}

