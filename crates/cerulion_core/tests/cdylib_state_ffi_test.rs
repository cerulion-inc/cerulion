#[test]
#[serial]
fn a_restored_value_reaches_the_cdylibs_own_tick_and_its_reconstruct_field_survives() {
    // The CONTROL first: the same graph with NO restore, so every moved number
    // below is attributable to the restore rather than to the fixture.
    let (mut control, _probe, control_seen) = built_probe("beh_ctl");
    // THREE steps for TWO deliveries: the sink drains one level behind the
    // probe's publish, so the last step's frame is still in flight.
    for _ in 0..3 {
        control.step(Duration::from_millis(10));
    }
    assert_eq!(
        control_seen.lock().expect("seen").clone(),
        // counter 0 then 1; empty history; empty label; `handle` = 7 from
        // `init()`, which the constructor's `Default` would have left at 0.
        vec![(0, 0, 0, 7), (1, 0, 0, 7)],
        "the un-restored control"
    );
    drop(control);

    let (mut runtime, _probe, seen) = built_probe("beh");
    let shape = {
        let guard = runtime
            .node_entry_arc_for_test("probe")
            .expect("probe entry");
        let guard = guard.lock().expect("probe");
        guard
            .state_shape()
            .expect("a macro cdylib declares a shape")
    };

    let mut anchors = std::collections::BTreeMap::new();
    anchors.insert(
        "probe".to_string(),
        framed(
            shape,
            &hand_payload(100, "resumed-state", &[1.5, 2.5, 3.5], &[(1, 10), (2, 20)]),
        ),
    );
    let report = runtime
        .restore_node_states(&anchors)
        .expect("the anchor applies");
    assert_eq!(report.restored, vec!["probe".to_string()]);
    assert!(report.declared_no_state.is_empty());

    for _ in 0..3 {
        runtime.step(Duration::from_millis(10));
    }
    assert_eq!(
        seen.lock().expect("seen").clone(),
        // counter resumed at 100 then 101; history length 3; label length 13;
        // and `handle + tags.len()` = 7 + 2 = 9 — the recording carried nothing
        // for `handle`, so a restore that clobbered it would read 2 here.
        vec![(100, 3, 13, 9), (101, 3, 13, 9)],
    );
}

