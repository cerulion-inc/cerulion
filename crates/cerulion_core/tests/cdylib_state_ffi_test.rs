#[test]
#[serial]
fn a_fresh_cdylib_nodes_capture_is_the_hand_built_default_encoding_and_its_port_contributes_nothing(
) {
    let (_runtime, probe, _seen) = built_probe("cap");

    let mut sink = VecSink::new();
    probe
        .lock()
        .expect("probe")
        .capture_state(&mut sink)
        .expect("a macro cdylib can capture");
    let captured = sink.into_inner();

    // A freshly constructed node: counter 0, empty label, empty history. The
    // `#[cerulion(reconstruct)]` handle is 7 after `init` and contributes
    // NOTHING, which the byte length proves — 8 + 4 + 0 + 4 + 4 = 20 bytes, with
    // no room for a fifth field and none for the `Quaternion` port's 32.
    assert_eq!(captured, hand_payload(0, "", &[], &[]));
    assert_eq!(captured.len(), 20, "captured: {captured:?}");
}

#[test]
#[serial]
fn a_capture_into_a_sink_too_small_reports_the_hosts_bound_not_a_broken_node() {
    let (_runtime, probe, _seen) = built_probe("small");

    // Four bytes cannot hold the leading `u64`, so the very first write refuses.
    let mut arena = [0u8; 4];
    let mut sink = BoundedSink::new(&mut arena);
    let err = probe
        .lock()
        .expect("probe")
        .capture_state(&mut sink)
        .expect_err("a 4-byte arena cannot take a u64");
    let text = err.to_string();
    assert!(
        text.contains("its buffer is too small"),
        "must blame the HOST's bound, not the node: {text}"
    );
    assert!(
        text.contains("probe") || text.contains("test_node_macro_state_cdylib"),
        "must name the node: {text}"
    );
}

#[test]
#[serial]
fn a_hash_like_container_refuses_before_building_its_sort_index_because_the_bound_crossed_the_wall()
{
    // WHY THIS ARM EXISTS. `capacity_hint` is the caller's bound carried across
    // the FFI as a scalar, because a callback ABI has nowhere else to put it.
    // Drop it and nothing about the VERDICT changes — the host's sink still
    // refuses, so the capture still fails — and the cost is invisible: the
    // cdylib builds a `Vec<&K>` sort index over the WHOLE container before
    // discovering the sink cannot take it (the ~240 MB-on-the-node-thread
    // case). One consequence IS observable, and it is what this arm reads: with
    // the bound, `guard_sort_scratch` calls `refuse()` and returns BEFORE the
    // container's four-byte count prefix is written; without it, that prefix
    // lands.
    let (_runtime, probe, _seen) = built_probe("hint");

    // Give the node a two-entry map. Its floor is 2 * (4 + 1) + 4 = 14 bytes,
    // so a sink with 4 bytes left provably cannot take it.
    probe
        .lock()
        .expect("probe")
        .restore_state(&hand_payload(1, "ab", &[], &[(1, 10), (2, 20)]))
        .expect("restore the map");

    let before_tags = hand_payload_before_tags(1, "ab", &[]);
    let mut arena = vec![0u8; before_tags.len() + 4];
    let mut sink = BoundedSink::new(&mut arena);
    let err = probe
        .lock()
        .expect("probe")
        .capture_state(&mut sink)
        .expect_err("the map cannot fit");
    assert!(
        err.to_string().contains("its buffer is too small"),
        "the host's bound, not a broken node: {err}"
    );
    assert_eq!(
        sink.len(),
        before_tags.len(),
        "the count prefix must NOT have been written: the container refused \
         before it built an index, which is only possible if the bound crossed \
         the FFI"
    );
    assert_eq!(&arena[..before_tags.len()], &before_tags[..]);
}

