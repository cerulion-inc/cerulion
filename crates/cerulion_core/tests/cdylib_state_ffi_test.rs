fn prefix_for(tag: &str) -> String {
    format!(
        "d6_{tag}_{}",
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .expect("clock")
            .as_nanos()
    )
}

/// One `probe` (the cdylib under test) publishing into one recording `sink`.
fn probe_graph(prefix: &str) -> GraphConfig {
    GraphConfig {
        level_assignments: None,
        network: None,
        process_groups: Default::default(),
        process_group_order: Default::default(),
        multi_publisher_topics: Vec::new(),
        name: None,
        identity: "d6".to_string(),
        prefix: prefix.to_string(),
        nodes: vec![
            NodeDef {
                ros2: None,
                id: "probe".to_string(),
                node_type: "probe".to_string(),
                inputs: vec![],
                outputs: vec![OutputDef {
                    name: "out".to_string(),
                    schema: "Quaternion".to_string(),
                    max_slice_len: None,
                    history_size: 0,
                    topic: None,
                }],
            },
            NodeDef {
                ros2: None,
                id: "sink".to_string(),
                node_type: "sink".to_string(),
                inputs: vec![InputDef {
                    name: "inp".to_string(),
                    source: "probe/out".to_string(),
                }],
                outputs: vec![],
            },
        ],
    }
}

type Seen = Arc<Mutex<Vec<(u64, u64, u64, u64)>>>;

fn build(prefix: &str, probe: Box<dyn NodeEntry>, seen: Seen) -> TransportResult<GraphRuntime> {
    let mut factories: IndexMap<String, Box<dyn NodeEntry>> = IndexMap::new();
    factories.insert("probe".to_string(), probe);

    let info = NodeInfo::from_names(vec!["inp".to_string()], vec![])
        .with_policy(MacroPolicy::Period { period_ms: 10 });
    let sink = ClosureNodeEntry::new(info, move |ctx| {
        let sub = ctx.subscriber("inp").expect("sink subscriber wired");
        let mut batch = Vec::new();
        let _ = sub.try_receive(|msg| {
            let p = msg.payload();
            let at = |i: usize| f64::from_le_bytes(p[i..i + 8].try_into().expect("8 bytes")) as u64;
            batch.push((at(0), at(8), at(16), at(24)));
        })?;
        seen.lock().expect("seen").extend(batch);
        Ok(())
    })
    .with_label("sink")
    .with_unified_drain(false);
    factories.insert("sink".to_string(), Box::new(sink));

    GraphRuntime::build_for_test(
        probe_graph(prefix),
        factories,
        Arc::new(VirtualClock::new()),
        16,
    )
}

/// Build a graph around the state cdylib and hand back the runtime plus a
/// clone of the `probe` entry, so a test can drive the FFI directly on the
/// SAME initialized instance the runtime holds.
fn built_probe(tag: &str) -> (GraphRuntime, Arc<Mutex<Box<dyn NodeEntry>>>, Seen) {
    let seen: Seen = Arc::new(Mutex::new(Vec::new()));
    let prefix = prefix_for(tag);
    let entry = DylibNodeEntry::load(&state_cdylib()).expect("state cdylib loads");
    let runtime = build(&prefix, Box::new(entry), Arc::clone(&seen)).expect("graph builds");
    let probe = runtime
        .node_entry_arc_for_test("probe")
        .expect("probe is in the node map");
    (runtime, probe, seen)
}

