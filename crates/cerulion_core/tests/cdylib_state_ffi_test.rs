#[test]
#[serial]
fn a_macro_cdylib_reports_its_own_inline_safety_rather_than_the_hosts_safe_default() {
    // Without `cerulion_node_inline_safe` every cdylib node inherits the host's
    // safe default (`false`), so the whole INLINE carrier is dead code on a real
    // graph — every node takes `fork(2)` at every cadence. And the failure is
    // SILENT: the anchors still appear, with byte-identical contents, because
    // both carriers run the same generated encoder. Nothing in a bag, a log or a
    // test of the capture ITSELF can see the difference.
    //
    // The fixture is plain data — four owned fields, no lock anywhere in the
    // state graph — so its `INLINE_SAFE` is TRUE, and reading `false` here is
    // exactly the silent degradation above.
    let (_runtime, probe, _seen) = built_probe("insafe");
    assert!(
        probe.lock().expect("probe").inline_safe(),
        "a plain-data macro cdylib must report itself inline-safe; `false` here is the \
         host's default showing through, which costs a fork(2) per anchor and looks \
         identical in the bag"
    );
}

#[test]
#[serial]
fn a_macro_cdylib_answers_the_pre_fork_lock_probe_over_its_own_state() {
    // The pre-fork lock probe, across the wall. The node's state graph holds no lock, so it
    // is quiescent — and the answer must come from the CDYLIB rather than from
    // the host's default, which happens to agree. The disagreeing arm is the
    // uninitialized one below, which no default can produce.
    let (_runtime, probe, _seen) = built_probe("probe");
    assert!(
        probe.lock().expect("probe").cer_probe(),
        "a lock-free node's state graph is quiescent at a boundary"
    );
}

#[test]
#[serial]
fn an_uninitialized_cdylib_is_not_quiescent_because_nothing_can_show_that_it_is() {
    // THE arm that separates a real answer from the trait's default. A node that
    // has not been `init`'d has no handle, so the probe cannot be asked about any
    // instance — and the host must say NOT QUIESCENT rather than fall back to the
    // optimistic default.
    //
    // The cost of that answer is one skipped anchor. The cost of the other is a
    // child that inherits a held lock: a fork child has exactly one thread, so
    // nothing can ever release it, and it wedges until the watchdog SIGKILLs it
    // five seconds later — reported as a stalled encoder that never ran.
    let entry = DylibNodeEntry::load(&state_cdylib()).expect("state cdylib loads");
    assert!(
        entry.inline_safe(),
        "the TYPE-level const is answerable without an instance, and must be"
    );
    assert!(
        !entry.cer_probe(),
        "the INSTANCE-level probe is not, and an unanswerable probe must read \
         NOT-quiescent"
    );
}

#[test]
#[serial]
fn a_symbol_less_cdylib_forks_and_is_believed_quiescent() {
    // BACK-COMPAT, and the two defaults pull in opposite directions on purpose.
    //
    // `inline_safe` defaults FALSE: a cdylib that has not proved it can be
    // encoded on the node thread must not claim it, and being wrong costs a
    // `fork(2)` rather than a wrong capture.
    //
    // `cer_probe` defaults TRUE: such a node declares no state graph at all, so
    // there is nothing for a probe to be true OF — and refusing on its behalf
    // would skip every anchor of every OTHER node in the process, for the life of
    // the run, on behalf of a node that contributes none. The residual is the
    // design's documented one: it is covered by the child's progress watchdog
    // instead.
    let entry = DylibNodeEntry::load(&symbol_less_cdylib()).expect("raw-FFI cdylib loads");
    assert!(
        !entry.inline_safe(),
        "a cdylib that exports no inline-safety claim must not be credited with one"
    );
    assert!(
        entry.cer_probe(),
        "and one that declares no state graph must not veto the whole anchor"
    );
    // ANTI-TAUTOLOGY: it really is the symbol-less fixture, not a load that
    // quietly failed into defaults.
    assert!(
        entry.state_shape().is_none(),
        "the raw-FFI fixture declares no state either — if it did, this is the \
         wrong library"
    );
}
