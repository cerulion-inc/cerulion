fn capture(value: &impl CerulionState) -> Vec<u8> {
    let mut sink = VecSink::new();
    value
        .cer_capture(&mut sink)
        .expect("unbounded capture cannot fail");
    sink.into_inner()
}

#[test]
fn the_last_of_exactly_max_variants_rides_tag_255_and_round_trips() {
    // Hand oracle: a unit variant is its tag byte and nothing else, and the
    // 256th variant's tag is the largest a byte can hold.
    assert_eq!(capture(&ExactlyMaxVariants::V0), vec![0]);
    assert_eq!(capture(&ExactlyMaxVariants::V255), vec![255]);

    let bytes = capture(&ExactlyMaxVariants::V255);
    let mut cursor = StateCursor::new(&bytes);
    let decoded = ExactlyMaxVariants::cer_read(&mut cursor).expect("decode");
    cursor.finish().expect("blob fully consumed");
    assert_eq!(decoded, ExactlyMaxVariants::V255);
}

#[test]
fn a_truncated_blob_is_still_reported_when_every_tag_is_a_real_variant() {
    // With all 256 tags spoken for there is no INVALID tag to report, so the
    // only decode failure left must still be loud rather than a silent
    // default: an empty blob is `Truncated`, never variant zero.
    let mut cursor = StateCursor::new(&[]);
    assert!(matches!(
        ExactlyMaxVariants::cer_read(&mut cursor),
        Err(StateError::Truncated { .. })
    ));
}
