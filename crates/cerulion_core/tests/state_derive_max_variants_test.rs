//! The 256-variant BOUNDARY, compiled for real.
//!
//! `MAX_ENUM_VARIANTS` is 256 and the guard is `>`, so exactly 256 variants
//! are ACCEPTED — and 256 one-byte tags exhaust `u8`, which leaves the
//! derive's invalid-tag wildcard arm genuinely unreachable. A review read that
//! and predicted a `BUILD_FAILURE`: `unreachable_patterns` is warn-by-default,
//! so the boundary enum the derive explicitly accepts would fail
//! `cargo clippy --workspace --all-targets -- -D warnings`.
//!
//! MEASURED, and it does NOT: this file compiles clean under that exact gate.
//! The lint is real — a HAND-WRITTEN 256-arm `match` on a `u8` followed by a
//! wildcard is rejected by `rustc -D warnings` with "no value can reach this"
//! — but rustc suppresses it for code expanded from a macro in ANOTHER crate,
//! and `cerulion_macros` is always another crate: to `cerulion_core` here, and
//! to every user's node crate. So the wildcard costs a dead arm rustc drops,
//! never a build.
//!
//! The file EARNS ITS KEEP as the standing evidence for both halves. It is a
//! real compilation of the boundary — so if rustc ever stops suppressing the
//! lint, the CI `lint` job says so instead of a user's build being the first
//! to find out — and it asserts the ENCODING at the boundary, which compiling
//! proves nothing about: that the 256th variant really rides tag 255, that it
//! round-trips, and that with every tag spoken for the remaining decode
//! failure is still loud rather than a silent variant zero.

